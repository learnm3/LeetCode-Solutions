/*
 * @lc app=leetcode.cn id=41 lang=cpp
 *
 * [41] 缺失的第一个正数
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做背包系统的"物品 ID 完整性检查"。
 * 背包有 N 个格子，物品 ID 从 1 开始递增发放。某次数据
 * 异常导致部分物品 ID 缺失或错乱。你需要在不分配额外内存
 * 的条件下（内存紧张，背包可能有几万个格子），找出第一个
 * 缺失的 ID（最小的未出现的正整数）。
 *
 * 游戏开发中同样的场景：
 * - 道具 ID 连续性校验（热更新后 ID 表是否损坏）
 * - 任务 ID 检查：链式任务 ID 必须从 1 连续
 * - 关卡 ID 完整性：确定第一个未使用的关卡 ID
 * - 成就 ID 序列校验
 * - 技能 ID 连续性：技能树重排后检查空洞
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一个未排序的整数数组，找出其中没有出现的最小正整数。
 * 要求 O(n) 时间，O(1) 额外空间。
 *
 * 示例：
 *   输入: [3, 4, -1, 1]
 *   输出: 2
 *
 *   输入: [1, 2, 0]
 *   输出: 3
 *
 * ============================================================
 * 核心思维：原地哈希（把数字放到对应索引上）
 * ============================================================
 *
 * 关键洞察：
 *   一个长度为 n 的数组，缺失的第一个正整数一定在 [1, n+1]
 *   这个范围内。因为最坏情况是数组正好是 [1, 2, ..., n]，
 *   此时答案是 n+1。
 *
 * 所以，大于 n 和小于等于 0 的数字都不需要关心。
 *
 * 核心操作：让每个满足 1 <= x <= n 的数字 x 放到 index = x-1 的位置。
 *   目标: nums[i] = i + 1
 *
 * 置换过程（nums = [3, 4, -1, 1]）：
 *
 *   i=0: nums[0]=3, 3 应该在 index 2
 *        swap(nums[0], nums[2]) → [-1, 4, 3, 1]
 *        nums[0]=-1，无效数字（<=0），跳过
 *
 *   i=1: nums[1]=4, 4 应该在 index 3
 *        swap(nums[1], nums[3]) → [-1, 1, 3, 4]
 *        nums[1]=1, 1 应该在 index 0
 *        swap(nums[1], nums[0]) → [1, -1, 3, 4]
 *        nums[1]=-1，跳过
 *
 *   i=2: nums[2]=3, 已经在 index 2 ✅
 *
 *   i=3: nums[3]=4, 已经在 index 3 ✅
 *
 *   最终: [1, -1, 3, 4]
 *
 *   遍历: i=0→nums[0]=1 ✅, i=1→nums[1]=-1 != 2 → 答案是 2 ✅
 *
 * 为什么用 while 而非 if？
 *   因为 swap 后，新换来的数字可能也需要归位。
 *   比如上例中，换完得到 nums[1]=1，还需要把 1 放到 index 0。
 *   所以 while 一直换到当前位置放的是无效数字或正确数字为止。
 *
 * ============================================================
 * 注意事项和易错点
 * ============================================================
 *
 *   while 条件: nums[i] > 0 && nums[i] <= n && nums[nums[i]-1] != nums[i]
 *
 *   - nums[i] > 0 && nums[i] <= n: 在有效范围内
 *   - nums[nums[i]-1] != nums[i]: 目标位置还不是它（防止无限循环）
 *     比如 [1,1] 的情况，如果目标位置已经是 1 了，再 swap 会死循环
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int firstMissingPositive(vector<int>& nums) {
        int n = nums.size();

        // ---- ① 原地哈希：把每个有效数字放到它该在的索引 ----
        //     数字 x 应该放在 index = x-1
        for (int i = 0; i < n; ++i) {
            // 用 while：换进来的新数字可能也需要归位
            while (nums[i] > 0 && nums[i] <= n && nums[nums[i] - 1] != nums[i]) {
                swap(nums[i], nums[nums[i] - 1]);
            }
        }

        // ---- ② 找到第一个"货不对板"的位置 ----
        for (int i = 0; i < n; ++i) {
            if (nums[i] != i + 1) {
                return i + 1;  // 缺失的正整数
            }
        }

        // ---- ③ 全部正确 → 缺失的是 n+1 ----
        return n + 1;
    }
};
// @lc code=end
