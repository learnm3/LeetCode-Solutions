/*
 * @lc app=leetcode.cn id=438 lang=cpp
 *
 * [438] 找到字符串中所有字母异位词
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 聊天敏感词系统第三弹（接 44、49 题）。
 * 现在不只是判断单个词是不是异位词，而是要在整段聊天文本中
 * 实时扫描——找出"原文中哪些位置开始，连续几个字符恰好是
 * 敏感词的一种字母重排"。
 *
 * 比如敏感词 p = "abc"，玩家输入 s = "cbaebabacd"，
 * 需要在 s 中找出所有起始位置，使得该位置开始的 3 个字符
 * 恰好是 "abc" 的异位词（= 字母组成完全相同）。
 *
 * 游戏开发中的同样场景：
 * - 连招检测：在按键序列中找出所有"目标连招的乱序片段"
 * - 聊天过滤：扫描整段消息中所有敏感词变体的位置
 * - 密码匹配：在输入序列中找出所有密码重排的起始点
 * - 掉落序列检测：在怪物掉落日志中找特定组合的连续区间
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定字符串 s 和 p，找到 s 中所有 p 的异位词的起始下标。
 * 异位词 = 字母组成完全相同，顺序可以不同。
 *
 * 示例：
 *   输入: s = "cbaebabacd", p = "abc"
 *   输出: [0, 6]
 *   解释: 从下标 0 开始的 "cba" 是 "abc" 的异位词
 *         从下标 6 开始的 "bac" 是 "abc" 的异位词
 *
 * ============================================================
 * 核心思维：定长滑动窗口 + 频次数组
 * ============================================================
 *
 * 异位词判断不需要真的排序——只需要"每种字母出现次数相同"。
 * 所以我们维护两个长度为 26 的数组（a~z 各一个格），
 * 分别统计目标串 p 和当前窗口中每种字母的出现次数。
 * 如果两个数组完全一样，那就是异位词。
 *
 * 窗口怎么滑？
 *   [c b a] e b a b a c d   ← 初始窗口 [0, 2]
 *    入: c, b, a 各 +1
 *
 *   c [b a e] b a b a c d   ← 窗口右移一格 [1, 3]
 *    出: c -1    入: e +1
 *
 *   c b [a e b] a b a c d   ← 窗口右移一格 [2, 4]
 *    出: b -1    入: b +1
 *
 *   ...每次只改两个字母，然后比较两个频次数组
 *
 * ============================================================
 * C++ 零基础语法讲解
 * ============================================================
 */

/*
 * 【头文件】
 *   <vector> → 动态数组
 *   <string> → C++ 字符串类型
 */
#include <vector>
#include <string>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【vector<int> findAnagrams(string s, string p)】
     *
     *   返回值 vector<int> → 整数数组，存放所有异位词的起始下标
     *   参数 s → 原文（要被扫描的长字符串）
     *   参数 p → 目标模式串（要找它的异位词）
     *
     *   注意：string 不是基本类型，和 int 不一样。
     *         string 是一个"字符的数组"，类似 vector<char>。
     *         s[0] 取第一个字符，s.size() 返回长度。
     */
    vector<int> findAnagrams(string s, string p) {

        /*
         * 【vector<int> result;】
         *   存放所有匹配的起始下标。
         *   例：找到下标 0 和 6 → result = [0, 6]
         */
        vector<int> result;

        /*
         * 【int sLen = s.size(), pLen = p.size();】
         *   保存两个字符串的长度。
         *
         *   为什么存到变量里？
         *     一会要反复用到，每次写 s.size() 也可以但更啰嗦。
         */
        int sLen = (int)s.size(), pLen = (int)p.size();

        /*
         * 【if (sLen < pLen) return result;】
         *   原文字符串比目标串还短 → 不可能包含异位词 → 返回空。
         *   提前退出，避免后面越界。
         */
        if (sLen < pLen) return result;

        /*
         * 【vector<int> pCount(26, 0);】
         *   目标串 p 的字母频次数组。
         *
         *   逐段拆解：
         *
         *   vector<int> → 装整数的动态数组
         *
         *   pCount → 变量名（= "p 的计数"）
         *
         *   (26, 0) → 构造函数参数：
         *      第一个参数 26 = 数组长度（26 个英文字母）
         *      第二个参数 0  = 每个元素的初始值
         *      等价于声明一个长度为 26 的数组，每个格子初始为 0。
         *
         *      这个构造的写法别和初始化列表混淆：
         *        vector<int> v(26, 0);   ← 26 个元素，每个都是 0
         *        vector<int> v{1, 2, 3}; ← 3 个元素，值分别是 1, 2, 3
         *
         *   下标含义：
         *     pCount[0] = 'a' 出现的次数
         *     pCount[1] = 'b' 出现的次数
         *     ...
         *     pCount[25] = 'z' 出现的次数
         */
        vector<int> pCount(26, 0);

        /*
         * 【vector<int> wCount(26, 0);】
         *   滑动窗口的字母频次数组。
         *   wCount = window count（窗口计数）。
         *   和 pCount 完全相同的结构，但统计的是当前窗口内的字母。
         *   窗口长度 = pLen（和目标串一样长）。
         */
        vector<int> wCount(26, 0);

        /*
         * ---- 初始化：把 p 的所有字符 + s 中第一个窗口的字符 都计上数 ----
         *
         * 【for (int i = 0; i < pLen; ++i) { ... }】
         *   同时做两件事：
         *     ① 统计 p 中每个字母的出现次数（这个只需做一次）
         *     ② 统计 s 的前 pLen 个字符（初始窗口）
         */
        for (int i = 0; i < pLen; ++i) {

            /*
             * 【pCount[p[i] - 'a']++;】
             *   把 p 的第 i 个字符转换成数组下标，对应格子计数 +1。
             *
             *   逐段拆解：
             *
             *   p[i] → 字符串 p 的第 i 个字符（下标从 0 开始）。
             *           例：p = "abc", p[0] = 'a', p[1] = 'b', p[2] = 'c'。
             *
             *   字符在 C++ 里实际上是一个整数（ASCII 码）。
             *     'a' 的 ASCII 码是 97
             *     'b' 的 ASCII 码是 98
             *     'c' 的 ASCII 码是 99
             *     ...
             *     'z' 的 ASCII 码是 122
             *
             *   那么 p[i] - 'a' 是什么意思？
             *     就是当前字符的 ASCII 码 减去 'a' 的 ASCII 码（97）。
             *
             *     例：'a' - 'a' = 97 - 97 = 0 → 下标 0（第一个格子）
             *         'b' - 'a' = 98 - 97 = 1 → 下标 1（第二个格子）
             *         'c' - 'a' = 99 - 97 = 2 → 下标 2（第三个格子）
             *         'z' - 'a' = 122 - 97 = 25 → 下标 25（最后一个格子）
             *
             *     所以 pCount[0] 统计 'a'，pCount[1] 统计 'b'，以此类推。
             *
             *   ++ → 自增运算符。pCount[x]++ 等价于 pCount[x] = pCount[x] + 1。
             *
             *   例：p = "aba"
             *     i=0: p[0]='a' → pCount['a'-'a']++ = pCount[0]++ → pCount[0]=1
             *     i=1: p[1]='b' → pCount['b'-'a']++ = pCount[1]++ → pCount[1]=1
             *     i=2: p[2]='a' → pCount['a'-'a']++ = pCount[0]++ → pCount[0]=2
             *     结果: pCount = [2, 1, 0, 0, ..., 0]  (2个a, 1个b)
             */
            ++pCount[p[i] - 'a'];

            /*
             * 【++wCount[s[i] - 'a'];】
             *   同理，把 s 的前 pLen 个字符放进窗口计数。
             *
             *   例：s = "cbaebabacd", pLen = 3
             *     i=0: s[0]='c' → wCount['c'-'a']++ = wCount[2]++
             *     i=1: s[1]='b' → wCount['b'-'a']++ = wCount[1]++
             *     i=2: s[2]='a' → wCount['a'-'a']++ = wCount[0]++
             *     初始窗口: wCount = [1, 1, 1, 0, ..., 0]  (窗口"cba": 各1个)
             */
            ++wCount[s[i] - 'a'];
        }

        /*
         * 【if (pCount == wCount) result.push_back(0);】
         *   检查初始窗口（下标 0 开始）是否是异位词。
         *
         *   == → 等于判断。vector 的 == 操作符会逐个元素比较。
         *         如果两个数组每个位置的数值都相同，返回 true。
         *         例：[1,1,1,0,...] == [1,1,1,0,...] → true!
         *
         *   如果是异位词，把起始下标 0 放进结果。
         *
         *   .push_back(0) → 把 0 加到 result 末尾。
         *                    result 从 [] 变成 [0]。
         */
        if (pCount == wCount) result.push_back(0);

        /*
         * ---- 滑动窗口：窗口每次右移一格 ----
         *
         * 【for (int i = pLen; i < sLen; ++i) { ... }】
         *   i 从 pLen 开始（窗口外的第一个字符），一直走到字符串末尾。
         *
         *   初始窗口覆盖 s[0] ~ s[pLen-1]，现在要滑到 s[1] ~ s[pLen]。
         *   i 指向"新加入窗口的字符"。
         */
        for (int i = pLen; i < sLen; ++i) {

            /*
             * 【++wCount[s[i] - 'a'];】
             *   新字符进入窗口（窗口右边界 +1）。
             *   把新字符的计数 +1。
             *
             *   例：窗口从 [c,b,a] 滑到 [b,a,e], i=3, s[3]='e'
             *     wCount['e'-'a']++ = wCount[4]++ = 1
             */
            ++wCount[s[i] - 'a'];

            /*
             * 【--wCount[s[i - pLen] - 'a'];】
             *   旧字符离开窗口（窗口左边界 -1）。
             *   把离开窗口的那个字符的计数 -1。
             *
             *   逐段拆解：
             *
             *   i - pLen → 离开窗口的那个字符的下标。
             *               i 是窗口右端再往右一格，窗口左端 = i - pLen。
             *
             *               例：pLen=3, i=3
             *                 离开的是 s[3-3] = s[0] = 'c'
             *
             *   -- → 自减运算符。等价于 wCount[x] = wCount[x] - 1。
             *
             *   例：s[0]='c' → wCount['c'-'a']-- = wCount[2]-- = 0
             */
            --wCount[s[i - pLen] - 'a'];

            /*
             * 【if (pCount == wCount) result.push_back(i - pLen + 1);】
             *   窗口滑动完毕，检查新窗口是否是异位词。
             *
             *   i - pLen + 1 → 新窗口的起始下标。
             *     i 是窗口右边界外的下一个字符
             *     窗口左边界 = i - pLen
             *     窗口起始 = i - pLen + 1?
             *
             *     仔细想：当 i = pLen 时:
             *       窗口覆盖 s[0..pLen-1]，还没滑，这是初始窗口。
             *       当 i = pLen 进入循环时:
             *         加入 s[pLen]，移出 s[0]
             *         新窗口覆盖 s[1..pLen]，起始 = 1
             *         1 = pLen - pLen + 1 = i - pLen + 1 ✓
             *
             *   result.push_back(这个起始下标);
             */
            if (pCount == wCount) result.push_back(i - pLen + 1);
        }

        /*
         * 【return result;】
         *   返回所有匹配的起始下标。
         */
        return result;
    }
};
// @lc code=end
