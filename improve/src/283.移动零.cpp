/*
 * @lc app=leetcode.cn id=283 lang=cpp
 *
 * [283] 移动零
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做"背包碎片整理"功能。
 * 背包有 N 个格子，有些格子是空的（值为 0），有些有物品（非 0）。
 * 整理功能要求：把所有有物品的格子挪到前面，空格子全部挤到
 * 后面，且物品之间的相对顺序不能变。
 *
 * 游戏开发中的同样场景：
 * - 背包整理：有效物品在前，空位在后
 * - 技能栏整理：已装备技能在前，空槽位在后
 * - UI 按钮排序：启用的按钮在前，禁用的挪到最后
 * - 粒子系统回收：活跃粒子集中到数组前部，死粒子清到尾部
 * - 排行榜：非零分的在前，零分垫底
 * - 任务列表：未完成的任务在前，已完成/失效的排后面
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定数组 nums，把所有 0 移到数组末尾，同时保持非零元素
 * 的相对顺序。必须原地操作（不创建新数组）。
 *
 * 示例：
 *   输入: [0, 1, 0, 3, 12]
 *   输出: [1, 3, 12, 0, 0]
 *
 * ============================================================
 * 核心思维：双指针——一个找"非零"，一个记"该放哪"
 * ============================================================
 *
 * 想象你有两排格子，你要把非零的物品往前挪：
 *
 *   insertPos  → 指向"下一个非零元素应该放的位置"
 *   i          → 遍历整个数组，寻找非零元素
 *
 * 每找到一个非零元素，就把它和 insertPos 处的元素交换，
 * 然后 insertPos 往前移一格。
 *
 * 图解过程 [0, 1, 0, 3, 12]：
 *
 *   初始: insertPos=0
 *
 *   i=0: nums[0]=0 → 跳过
 *        [0, 1, 0, 3, 12]   insertPos=0
 *
 *   i=1: nums[1]=1 → 交换 nums[0]↔nums[1]
 *        [1, 0, 0, 3, 12]   insertPos=1
 *
 *   i=2: nums[2]=0 → 跳过
 *        [1, 0, 0, 3, 12]   insertPos=1
 *
 *   i=3: nums[3]=3 → 交换 nums[1]↔nums[3]
 *        [1, 3, 0, 0, 12]   insertPos=2
 *
 *   i=4: nums[4]=12 → 交换 nums[2]↔nums[4]
 *        [1, 3, 12, 0, 0]   insertPos=3
 *
 * 最终: [1, 3, 12, 0, 0] ✓
 * insertPos=3 后面的全是 0。
 *
 * ============================================================
 * C++ 零基础语法讲解
 * ============================================================
 */

/*
 * 【头文件】
 *   <vector>   → 动态数组，本题用它是因为参数是 vector<int>&
 *   <algorithm> → 本题用到了 swap() 函数
 */
#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【void moveZeroes(vector<int>& nums)】
     *
     *   逐段拆解：
     *
     *   void → 返回值类型。"void" 的意思是"空/没有返回值"。
     *           这个函数不返回任何东西——它直接修改传进来的数组。
     *           之前的题返回值是 vector 或 int，这题是 void。
     *
     *           void 就像一个命令："去做这件事"，做完了就行，
     *           不需要报告结果。因为结果已经在 nums 里面了。
     *
     *   moveZeroes → 函数名。Move Zeroes = 移动零。
     *
     *   vector<int>& nums → 参数：整数数组的引用。
     *                        & 保证我们改的是原始数组，不是复制品。
     */
    void moveZeroes(vector<int>& nums) {

        /*
         * 【int insertPos = 0;】
         *   int       → 整数类型
         *   insertPos → 变量名（= "插入位置"）。
         *                指向"下一个非零元素应该放置的数组下标"。
         *   = 0       → 初始化为 0。最开始从数组头部开始放。
         *
         *   这个变量会在整个过程中从 0 慢慢增长，最终指向
         *   "第一个应该是 0 的位置"。
         *
         *   比如最后数组变成 [1,3,12,0,0]，insertPos 会是 3。
         */
        int insertPos = 0;

        /*
         * 【int n = nums.size();】
         *   int n         → 声明整数 n
         *   = nums.size() → 把数组长度赋值给 n。
         *                    .size() 返回 size_t 类型（无符号整数），
         *                    赋给 int 会有警告，写 (int) 转换一下更安全。
         *                    n = 5（因为有 5 个元素）
         *
         *   为什么要先存到变量 n 里？
         *     直接写在 for 循环条件里也行，但先存起来可以避免
         *     每次循环都调用 .size()（虽然对 vector 来说很快），
         *     更重要的是代码更清晰。
         */
        int n = nums.size();

        /*
         * 【for (int i = 0; i < n; ++i) { ... }】
         *   标准 for 循环（和第 1 题两数之和的写法一样）。
         *
         *   i 是遍历指针，从 0 走到 n-1。
         *   i 的角色是"侦察兵"：扫描数组，发现非零元素。
         */
        for (int i = 0; i < n; ++i) {

            /*
             * 【if (nums[i] != 0) { ... }】
             *   判断：当前位置的元素不是零吗？
             *
             *   != → 不等于运算符。
             *         如果左边和右边不相等，返回 true。
             *         例：5 != 0 → true,  0 != 0 → false
             *
             *   所以这个 if 的意思是："如果当前元素不是 0"。
             *   是 0 的话什么都不做，直接跳过。
             */
            if (nums[i] != 0) {

                /*
                 * 【swap(nums[i], nums[insertPos]);】
                 *   交换两个位置的值。
                 *
                 *   逐段拆解：
                 *
                 *   swap  → <algorithm> 头文件提供的交换函数。
     *            它会交换两个变量的值。内部实现大概长这样：
     *              temp = a;  a = b;  b = temp;
     *            我们不用自己写，直接调用。
     *
     *   nums[i]          → 当前找到的非零元素
     *   nums[insertPos]  → 插入位置上的元素（可能是 0 或非零）
     *
     *   交换效果（例）：
     *     交换前: nums[insertPos]=0, nums[i]=3
     *     交换后: nums[insertPos]=3, nums[i]=0
     *
     *   注意：当 i == insertPos 时（两个指针指向同一位置），
     *         swap 相当于自己和自己交换，效果等于什么都没做。
     *         这正是我们想要的——元素本来就在正确位置。
     */
                swap(nums[i], nums[insertPos]);

                /*
                 * 【++insertPos;】
                 *   插入位置往前移动一格。
                 *   等价于 insertPos = insertPos + 1。
                 *
                 *   为什么要在交换后 +1？
                 *     因为我们刚刚在 insertPos 这个位置放好了一个
                 *     非零元素，下一个非零元素应该放到下一个位置。
                 *
                 *   举例：insertPos=0, 放好 1 后 → insertPos=1
                 *         insertPos=1, 放好 3 后 → insertPos=2
                 */
                ++insertPos;
            }
        }

        /*
         * 循环结束后，不需要额外操作。
         * 所有非零元素已按顺序排在前面，零自动被挤到了后面。
         * 函数没有 return 语句（因为是 void 类型）。
         *
         * 最终结果（以 [0,1,0,3,12] 为例）：
         *   [1, 3, 12, 0, 0]
         *   insertPos = 3（第一个 0 的位置）
         */
    }
};
// @lc code=end
