/*
 * @lc app=leetcode.cn id=239 lang=cpp
 *
 * [239] 滑动窗口最大值
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做"帧率监控面板"。
 * 游戏过去 N 帧的每帧耗时是：
 *   [1, 3, -1, -3, 5, 3, 6, 7]（毫秒）
 * 你需要在面板上滚动显示"最近 3 帧的最差耗时"——
 * 这是个滑动窗口，每帧都要知道窗口内的最大值。
 *
 * 游戏开发中的同样场景：
 * - 帧率监控：最近 K 帧的最大帧时间（卡顿检测）
 * - DPS 仪表盘：最近 K 秒的峰值伤害
 * - 网络延迟：最近 K 个包的最大延迟
 * - 内存监控：最近 K 帧的最大内存占用
 * - 战斗日志：每个 K 秒窗口内的最大暴击伤害
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定数组 nums 和窗口大小 k，窗口从左往右滑动，
 * 返回每个窗口中最大值的列表。
 *
 * 示例：nums = [1, 3, -1, -3, 5, 3, 6, 7], k = 3
 *   窗口1: [1,  3, -1] → max=3
 *   窗口2:   [3, -1, -3] → max=3
 *   窗口3:     [-1, -3, 5] → max=5
 *   窗口4:        [-3, 5, 3] → max=5
 *   窗口5:            [5, 3, 6] → max=6
 *   窗口6:              [3, 6, 7] → max=7
 *   输出: [3, 3, 5, 5, 6, 7]
 *
 * ============================================================
 * 核心思维：单调队列（deque）
 * ============================================================
 *
 * 暴力法：每个窗口扫一遍找最大 → O(n×k)，太慢。
 * 单调队列法：O(n)，每个元素只进队一次、出队一次。
 *
 * 核心想法：
 *   队列里只保留"有潜力成为某个窗口最大值"的元素，
 *   而且它们按从大到小排列。队头永远是当前窗口的最大值。
 *
 * 规则（三条）：
 *
 *   ① 新元素入队前：把队尾所有"比我小的"都踢掉。
 *      因为它们永远不会再成为最大值了——
 *      我比它们大，而且我比它们"活得久"（位置更靠右）。
 *
 *   ② 新元素入队：从队尾加入。
 *
 *   ③ 滑出窗口的元素：如果它恰好是队头（当前最大值），
 *      把它从队头踢掉。如果它不是队头，说明它早就被
 *      规则①踢出去了（被后面更大的挤掉了）。
 *
 * 图解 nums=[1,3,-1,-3,5,3,6,7], k=3：
 *
 *   队列里存的是"下标"（不是值），方便判断是否滑出窗口。
 *
 *   i=0, nums[0]=1
 *     队空 → 直接入队
 *     队列: [0(值=1)]                              窗口未满
 *
 *   i=1, nums[1]=3
 *     队尾 1 < 3 → 踢掉 1。队空 → 入队
 *     队列: [1(值=3)]                              窗口未满
 *
 *   i=2, nums[2]=-1
 *     队尾 3 > -1 → 不踢。入队
 *     队列: [1(值=3), 2(值=-1)]                     窗口[0..2] → max=3
 *
 *   i=3, nums[3]=-3
 *     窗口[1..3]: 下标 0 滑出了。队头下标 1 ≠ 0，不管。
 *     队尾 -1 > -3 → 不踢。入队
 *     队列: [1(值=3), 2(值=-1), 3(值=-3)]           窗口[1..3] → max=3
 *
 *   i=4, nums[4]=5
 *     窗口[2..4]: 下标 1 还在窗口内，不管。
 *     队尾 -3 < 5 → 踢掉! 队尾 -1 < 5 → 踢掉! 队尾 3 < 5 → 踢掉!
 *     队空 → 入队
 *     队列: [4(值=5)]                              窗口[2..4] → max=5
 *
 *   总结：任何时候，队列从队头到队尾是严格递减的，
 *         队头就是当前窗口的最大值。
 *
 * ============================================================
 * C++ 零基础语法讲解
 * ============================================================
 */

/*
 * 【头文件】
 *   <vector> → 动态数组（返回值、输入参数都是它）
 *   <deque>  → 双端队列（double-ended queue 的缩写，读作 "deck"）。
 *               和普通队列的区别：可以从两头插入和删除。
 *               普通队列只能从队尾进队头出，deque 两头都能操作。
 *
 *   deque 常用操作：
 *     .push_back(x)   → 从队尾加一个元素
 *     .pop_back()     → 从队尾删一个元素
 *     .push_front(x)  → 从队头加一个元素
 *     .pop_front()    → 从队头删一个元素
 *     .front()        → 查看队头元素（不删除）
 *     .back()         → 查看队尾元素（不删除）
 *     .empty()        → 队列是空的吗？返回 true 或 false
 *
 *   本题只用 push_back、pop_back、pop_front、front、back、empty。
 */
#include <vector>
#include <deque>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【vector<int> maxSlidingWindow(vector<int>& nums, int k)】
     *
     *   返回值 vector<int> → 每个窗口的最大值组成的数组
     *   参数 nums → 原始数据数组
     *   参数 k    → 窗口大小
     */
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {

        /*
         * 【vector<int> result;】
         *   存放所有窗口最大值的数组。
         *   例：k=3, n=8 → 窗口数 = 8-3+1 = 6 → result 长度会是 6。
         */
        vector<int> result;

        /*
         * 【deque<int> dq;】
         *   声明一个双端队列，名字叫 dq（deque 的缩写）。
         *
         *   这个队列里存的是"下标"（索引），不是值！
         *   因为我们需要用下标来判断"这个元素还在不在窗口内"。
         *   取值时用 nums[dq.front()] 来拿到最大值。
         *
         *   队列始终满足：
         *     nums[dq[0]] >= nums[dq[1]] >= nums[dq[2]] >= ...
         *     即：队头最大，往后递减。这叫"单调递减队列"。
         */
        deque<int> dq;

        /*
         * 【int n = nums.size();】
         *   数组长度，避免反复调用 .size()。
         */
        int n = nums.size();

        /*
         * 【for (int i = 0; i < n; ++i) { ... }】
         *   i 是当前窗口右边界（也是当前遍历到的下标）。
         *   窗口覆盖 [i-k+1, i]。
         */
        for (int i = 0; i < n; ++i) {

            /*
             * ---- 规则①：踢掉已经滑出窗口的队头 ----
             *
             * 【if (!dq.empty() && dq.front() < i - k + 1) { ... }】
             *
             *   逐段拆解：
             *
             *   !dq.empty() → 队列非空才需要检查。
             *     ! → 逻辑非。empty() 返回 true 时，!true = false。
             *         整体意思是"如果队列不为空"。
             *
             *   dq.front() → 取队头元素（队列最前面那个）。
             *                 这里队头存的是"下标"。
             *
             *   i - k + 1 → 当前窗口的左边界下标。
             *                例：k=3, i=3 → 左边界 = 3-3+1 = 1
             *                窗口覆盖 [1, 2, 3]。
             *
             *   dq.front() < i - k + 1
             *     队头的下标 < 当前窗口左边界 → 队头已经滑出窗口了！
             *
             *   如果成立 → dq.pop_front(); 把队头删掉。
             */
            if (!dq.empty() && dq.front() < i - k + 1) {
                dq.pop_front();  // 扔掉队头（它已经不在窗口内了）
            }

            /*
             * ---- 规则②：踢掉队尾所有比当前元素小的 ----
             *
             * 【while (!dq.empty() && nums[dq.back()] <= nums[i]) { ... }】
             *
             *   逐段拆解：
             *
             *   !dq.empty() → 队列非空
             *
             *   dq.back() → 取队尾元素（队列最后面的那个下标）
             *
             *   nums[dq.back()] → 队尾下标对应的值
             *
             *   <= nums[i] → 队尾的值 ≤ 当前值吗？
             *     <= → 小于等于。左边 ≤ 右边为 true。
             *
             *   为什么用 <= 而不是 <？
             *     相等也要踢掉！因为同样大的值，新的比旧的"活得久"
             *     （位置更靠右，更晚滑出窗口），旧的没用了。
             *
             *   为什么用 while 而不是 if？
             *     可能队尾连续好几个都比当前值小，需要全部踢掉。
             *     例：队列 [3, 2, 1]，新元素 5
             *         第1轮: 队尾 1 < 5 → 踢
             *         第2轮: 队尾 2 < 5 → 踢
             *         第3轮: 队尾 3 < 5 → 踢
             *         队空了 → 退出 while
             */
            while (!dq.empty() && nums[dq.back()] <= nums[i]) {
                dq.pop_back();   // 踢掉队尾
            }

            /*
             * ---- 规则③：新元素入队 ----
             *
             * 【dq.push_back(i);】
             *   把当前下标加到队尾。
             *   此时队列一定是从大到小排好的（因为前面踢掉了所有比我小的）。
             */
            dq.push_back(i);

            /*
             * ---- 取当前窗口的最大值 ----
             *
             * 【if (i >= k - 1) { ... }】
             *   窗口还没满 k 个元素时不取结果。
             *   例如 k=3，i=0,1 时窗口不满，到 i=2 时才形成第一个完整窗口。
             *
             *   result.push_back(nums[dq.front()]);
             *     dq.front() → 队头下标
             *     nums[队头下标] → 队头下标对应的值（= 当前窗口最大值）
             *     .push_back() → 把最大值加入结果数组
             */
            if (i >= k - 1) {
                result.push_back(nums[dq.front()]);
            }
        }

        /*
         * 【return result;】
         */
        return result;
    }
};
// @lc code=end
