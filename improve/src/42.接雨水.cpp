/*
 * @lc app=leetcode.cn id=42 lang=cpp
 *
 * [42] 接雨水
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你在做开放世界游戏的"动态水域系统"。
 * 给定一个高度图（柱状图），下雨后洼地会积水。你需要计算
 * 总积水量的体积（每个柱子宽为 1，积水高度受两侧最高柱子
 * 限制）。经典的双指针/单调栈问题。
 *
 * 游戏开发中同样的场景：
 * - 地形积水模拟：洼地自动积水，影响角色移动
 * - 关卡地形自动填充：在凹坑区域生成湖泊
 * - 光线追踪中的高度场阴影计算
 * - 背包容量可视化：柱状图表示各物品占用，"空隙"是可用空间
 * - UI 布局中的空白区域计算
 * - 描边/轮廓生成：柱状图的"包络线"计算
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一个非负整数数组，每个数代表柱子的高度（宽度为 1）。
 * 计算下雨后这些柱子之间能接多少雨水。
 *
 * 示例：
 *   输入: height = [0,1,0,2,1,0,1,3,2,1,2,1]
 *
 *   可视化（竖着看）：
 *            *
 *        *...*..*
 *    *.*..**.******   (. 是水)
 *   输出: 6
 *
 * ============================================================
 * 核心思维：双指针（对撞指针）
 * ============================================================
 *
 * 一个位置上能接多少水？
 *
 *   该位置的水量 = min(左侧最高, 右侧最高) - 当前高度
 *
 *   比如 height[2]=0:
 *     左侧最高 = max(0,1) = 1
 *     右侧最高 = max(2,1,0,1,3,2,1,2,1) = 3
 *     min(1, 3) - 0 = 1 ← 能接 1 格水 ✅
 *
 * 但如果对每个位置都扫描左右最高，就是 O(n²)。
 *
 * 双指针优化到 O(n)：
 *   核心观察：对于位置 i，它能不能接水，取决于 min(leftMax, rightMax)
 *   中的那个"短板"。
 *
 *   我们用 leftMax 记录左指针见过的最高高度，
 *      用 rightMax 记录右指针见过的最高高度。
 *
 *   如果 leftMax < rightMax:
 *     → 左指针 i 处的储水量完全由 leftMax 决定
 *        （因为右边就算有更高的墙，也被"短板"限制住了）
 *     → 水量 = leftMax - height[i]，然后 left++
 *
 *   如果 leftMax >= rightMax:
 *     → 右指针 j 处的储水量完全由 rightMax 决定
 *     → 水量 = rightMax - height[j]，然后 right--
 *
 * 为什么这样做是对的？
 *   就像两个人在两端注水，水的"上限"由低的那一端的墙决定。
 *   哪端的 max 低，就处理哪端，因为墙低的那个方向的柱子
 *   必定被 min(leftMax, rightMax) 限制。
 *
 * ============================================================
 * 图解执行过程（height = [0,1,0,2,1,0,1,3,2,1,2,1]）
 * ============================================================
 *
 *   L=0,R=11: h[0]=0< h[11]=1 → leftMax=0, res+=0, L=1
 *   L=1,R=11: h[1]=1>=h[11]=1 → rightMax=1, res+=1-1=0, R=10
 *   L=1,R=10: h[1]=1< h[10]=2 → leftMax=1, res+=1-1=0, L=2
 *   L=2,R=10: h[2]=0< h[10]=2 → leftMax=1, res+=1-0=1, L=3  (+1)
 *   L=3,R=10: h[3]=2>=h[10]=2 → rightMax=2, res+=2-2=0, R=9
 *   L=3,R=9:  h[3]=2> h[9]=1  → rightMax=2, res+=2-1=1, R=8  (+1)
 *   L=3,R=8:  h[3]=2>=h[8]=2 → rightMax=2, res+=2-2=0, R=7
 *   L=3,R=7:  h[3]=2< h[7]=3 → leftMax=2, res+=2-2=0, L=4  (leftMax 更新为 2)
 *   L=4,R=7:  h[4]=1< h[7]=3 → leftMax=2, res+=2-1=1, L=5  (+1)
 *   ...以此类推
 *
 *   最终 res = 6 ✅
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int trap(vector<int>& height) {
        int left = 0, right = height.size() - 1;
        int leftMax = 0, rightMax = 0;  // 左右见过的最高的墙
        int water = 0;

        while (left < right) {
            // ---- 哪边墙低就处理哪边 ----
            if (height[left] < height[right]) {
                // 左边是短板
                leftMax = max(leftMax, height[left]);    // 更新左 max
                water += leftMax - height[left];         // 累加当前柱子的水量
                ++left;
            } else {
                // 右边是短板
                rightMax = max(rightMax, height[right]); // 更新右 max
                water += rightMax - height[right];       // 累加当前柱子的水量
                --right;
            }
        }

        return water;
    }
};
// @lc code=end
