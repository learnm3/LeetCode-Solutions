/*
 * @lc app=leetcode.cn id=55 lang=cpp
 *
 * [55] 跳跃游戏
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 动作游戏的"位移可达性检测"。
 * 角色站在平台序列的最左边（下标 0），每个格子标注了
 * 从该位置最多能往前跳几格。程序需要快速判断：能否到
 * 达最右边的终点？
 *
 * 注意：本题（55）只问"能不能到"（true/false），
 * 而第 45 题问的是"最少几步到"。55 是 45 的简化版。
 *
 * 游戏开发场景：
 * - 平台跳跃：检测当前关卡理论上是否可通关
 * - 技能范围：敌方是否在某个技能的射程覆盖范围内
 * - 传送链：一串传送门能否让你从 A 岛跳到 Z 岛
 * - 资源规划：当前燃料沿途各站加油，能否跑完全程
 * - 关卡验证工具：策划放完跳板后，自动检测"能到达吗"
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定非负整数数组 nums，从下标 0 出发，nums[i] 表示
 * 在位置 i 最多能往前跳的距离。判断能否到达最后一个下标。
 *
 * 示例：
 *   [2, 3, 1, 1, 4] → true  (0→1→4)
 *   [3, 2, 1, 0, 4] → false (最远只能到 3，跨不过那个 0)
 *
 * ============================================================
 * 核心思维：维护"能到达的最远位置"
 * ============================================================
 *
 * 和 45 题同一个框架，但更简单——不需要数步数。
 *
 * 一个变量 farthest = 当前能到达的最远下标。
 * 遍历数组，每一步更新 farthest。
 *
 * 如果 i > farthest → 说明当前位置根本到不了 → false
 * 如果 farthest >= n-1 → 能到终点 → true
 *
 * 走一遍 [2, 3, 1, 1, 4]：
 *
 *   i=0: farthest = max(0, 0+2) = 2
 *   i=1: farthest = max(2, 1+3) = 4  → 4 >= 4(终点) → true
 *
 * 走一遍 [3, 2, 1, 0, 4]：
 *
 *   i=0: farthest = max(0, 0+3) = 3
 *   i=1: farthest = max(3, 1+2) = 3
 *   i=2: farthest = max(3, 2+1) = 3
 *   i=3: farthest = max(3, 3+0) = 3
 *   i=4: i(4) > farthest(3) → 位置 4 到不了 → false
 *
 * ============================================================
 * 和 45 题的对比
 * ============================================================
 *
 *   55 (本题): 只问"能不能"  → 一个变量 farthest，O(n)
 *   45 题:     问"最少几步"  → 三个变量 jumps/curEnd/curFarthest，O(n)
 *
 *   两道题合在一起就是游戏里完整的"寻路+步数优化"系统。
 *
 * ============================================================
 * 代码
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    bool canJump(vector<int>& nums) {
        int farthest = 0;  // 目前能到达的最远下标

        for (int i = 0; i < nums.size(); ++i) {
            // 当前位置都到不了，后面更别想了
            if (i > farthest) return false;

            // 从当前位置出发，能刷新最远记录吗？
            farthest = max(farthest, i + nums[i]);

            // 已经能到终点了，提前收工
            if (farthest >= (int)nums.size() - 1) return true;
        }

        return true;  // 循环跑完 = 必然到了终点
    }
};
// @lc code=end
