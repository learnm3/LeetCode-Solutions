/*
 * @lc app=leetcode.cn id=3 lang=cpp
 *
 * [3] 无重复字符的最长子串
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】MMO 聊天系统的脏词过滤与消息截断
 *
 * 你正在开发一款大型多人在线游戏的聊天系统。玩家输入的消息需要通过脏词过滤器，
 * 同时系统需要限制单条消息的最大长度。但产品经理提出了一个巧妙的需求：
 * "与其简单截断，不如找出消息中【不含重复字符的最长连续子串】作为消息预览，
 * 这样预览看起来更自然、更有信息量。"
 *
 * 例如玩家输入 "abcabcbb"，不含重复字符的最长子串是 "abc"，长度 3，
 * 聊天预览就显示这个子串，既紧凑又保留了最多的不同字符信息。
 *
 * 这个需求实际上就是 LeetCode 第 3 题的核心问题。
 *
 * 游戏开发中的类比场景：
 * - 技能连招系统：找出不重复使用同一技能的最长连招序列（避免"无限连"漏洞）
 * - 背包整理：在物品栏中找出不包含重复物品类型的最长连续排列
 * - UI 标签页：在固定宽度内展示尽可能多不重复的标签图标
 *
 * 【题目】
 * 给定一个字符串 s，找出其中不含有重复字符的最长子串的长度。
 *
 * 示例：
 *   输入: s = "abcabcbb"
 *   输出: 3  （最长子串 "abc"）
 *
 *   输入: s = "bbbbb"
 *   输出: 1  （最长子串 "b"）
 *
 *   输入: s = "pwwkew"
 *   输出: 3  （最长子串 "wke"）
 *
 * ===== 核心思维 =====
 *
 * 一、暴力法为什么不行？
 *
 * 最直接的想法：枚举所有子串起点 i 和终点 j，检查 s[i..j] 是否有重复字符。
 * 时间复杂度 O(n^3)，n=5万时根本无法接受（想象 5 万字的聊天记录）。
 *
 * 二、滑动窗口：像毛毛虫一样移动
 *
 * 想象一条毛毛虫在叶子上爬行：
 *   - 头部（右指针）向前探索，不断吃入新叶子（字符）
 *   - 如果吃到已经吃过的叶子种类 → 尾部（左指针）向前移动，吐出最前面的叶子
 *   - 虫子身体的长度就是当前"无重复子串"的长度
 *   - 记录虫子曾经达到的最大长度，就是答案
 *
 * 用双指针实现：
 *
 *   字符串:  a  b  c  a  b  c  b  b
 *            ↑  ↑                    → 窗口 "ab"，长度2，无重复 ✓
 *            L  R
 *
 *            ↑     ↑                 → 窗口 "abc"，长度3，无重复 ✓，更新答案=3
 *            L     R
 *
 *               ↑     ↑              → 窗口 "abca"，有重复！L 右移吐出 a
 *               L     R
 *
 *               ↑     ↑              → 窗口 "bca"，长度3，无重复 ✓
 *               L     R
 *
 * 三、数据结构选择
 *
 * 如何快速判断字符是否在窗口内？用哈希集合 unordered_set<char>：
 *   - 插入 O(1)，删除 O(1)，查询 O(1)
 *   - 窗口最多 128 个不同字符（ASCII），空间可忽略
 *
 * 更极致的优化：因为字符集有限（ASCII 128 / 扩展 ASCII 256），
 * 可以用长度为 128 的 bool 数组代替哈希表，避免哈希冲突开销。
 *
 * 四、复杂度分析
 *
 *   - 时间复杂度：O(n)。每个字符最多被左指针和右指针各访问一次。
 *   - 空间复杂度：O(min(n, 字符集大小))。最多存储 min(n, 128) 个字符。
 *
 * 五、可迁移模式 —— 滑动窗口模板
 *
 * 滑动窗口适用于"寻找满足某条件的连续子数组/子串"类问题：
 *
 *   初始化：左指针 L=0，窗口状态（哈希表/计数器）
 *   for 右指针 R 从 0 到 n-1:
 *       将 s[R] 加入窗口
 *       while 窗口不满足条件:
 *           移除 s[L]，L++
 *       更新答案（窗口长度 = R - L + 1）
 *
 * 相关 LeetCode 题：
 *   - 76. 最小覆盖子串（窗口包含所有目标字符）
 *   - 159. 至多包含两个不同字符的最长子串
 *   - 424. 替换后的最长重复字符
 *   - 438. 找到字符串中所有字母异位词
 */

#include <string>
#include <unordered_set>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int lengthOfLongestSubstring(string s) {
        // 使用 bool 数组替代哈希表，ASCII 字符集只需 128 位
        // 比 unordered_set 更轻量，无哈希开销
        bool inWindow[128] = {false};
        int n = s.size();
        int left = 0;      // 滑动窗口左边界
        int maxLen = 0;    // 记录最大窗口长度

        // 右指针遍历每个字符，尝试扩展窗口
        for (int right = 0; right < n; ++right) {
            char c = s[right];
            // 如果当前字符已在窗口中 → 收缩左边界直到重复字符被移除
            while (inWindow[c]) {
                inWindow[s[left]] = false;
                ++left;
            }
            // 将当前字符加入窗口
            inWindow[c] = true;
            // 更新最大长度：窗口段 [left, right] 内无重复
            maxLen = max(maxLen, right - left + 1);
        }
        return maxLen;
    }
};
// @lc code=end
