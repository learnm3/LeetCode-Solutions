/*
 * @lc app=leetcode.cn id=44 lang=cpp
 *
 * [44] 通配符匹配
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在给游戏聊天系统写"敏感词过滤 + 变体识别"模块。
 * 玩家会用各种方式绕过检测：
 *   "f*u*c*k"、 "f?ck"、 "f u c k"
 * 你需要一个通配符匹配引擎，判断玩家输入是否命中敏感词模式。
 *
 * 除此之外，游戏开发中同样的模式匹配逻辑还用在：
 * - 背包搜索："*剑*" 匹配所有带"剑"字的物品名
 * - 资源加载："Assets/Chars/<star>/Tex/<star>.png" 这种路径匹配
 * - 开发者控制台：heal* 匹配 heal/healall/heal_player
 * - 对话系统：NPC 对话选项的条件匹配
 *
 * ============================================================
 * 题目规则
 * ============================================================
 *
 * s: 待匹配的字符串（玩家输入）
 * p: 模式串（含通配符 ? 和 *）
 * ? : 匹配任意【单个】字符
 * * : 匹配任意【多个】字符（含 0 个）
 *
 * 要求：p 必须覆盖整个 s（从头到尾完全匹配）
 *
 * 示例：
 *   s="abc", p="a?c"    → true  (? 匹配 b)
 *   s="abc", p="a*"     → true  (* 匹配 bc)
 *   s="abc", p="*"      → true  (* 匹配整个 abc)
 *   s="ab",  p="?*"     → true  (? 匹配 a, * 匹配 b)
 *   s="abc", p="a*b?d"  → false (末尾的 d 对不上)
 *
 * ============================================================
 * 思路一：DP（动态规划）—— 好理解，适合讲思路
 * ============================================================
 *
 * 画个二维表：
 *   dp[i][j] = s 的前 i 个字符能否被 p 的前 j 个模式匹配
 *
 *   横轴: p 的字符
 *   纵轴: s 的字符
 *
 *   以 s="abc", p="a*?" 为例：
 *
 *        ""  a  *  ?
 *   ""   T  F  T  F    ← 空串只能被全部是 * 的模式匹配
 *   a    F  T  T  F
 *   b    F  F  T  T    ← * 吞掉 b, ? 吞掉 c
 *   c    F  F  T  T
 *
 * 递推公式（三个入口）：
 *
 *   1) p[j-1] 是普通字符 → dp[i][j] = dp[i-1][j-1] && s[i-1]==p[j-1]
 *      你和我一样，且前面也匹配 → 我匹配
 *
 *   2) p[j-1] 是 ?        → dp[i][j] = dp[i-1][j-1]
 *      你是啥我都吃，只要前面匹配 → 我匹配
 *
 *   3) p[j-1] 是 *        → dp[i][j] = dp[i][j-1] || dp[i-1][j]
 *                              |              └─ * 吃掉当前字符（s 往前缩一格，* 还在）
 *                              └─ * 当空气（跳过 *，用 * 前面的模式继续匹配）
 *
 * DP 是 O(m×n)，能过 LeetCode 但不算最优。
 *
 * ============================================================
 * 思路二：贪心 + 回溯 —— 面试最优解，O(m+n)
 * ============================================================
 *
 * 核心直觉：
 *   * 是唯一能"匹配任意长度"的牌。遇到 * 时，我们不知道它该吃几个字符。
 *   那就先让它吃 0 个试试，走不通再"回退"让它多吃一个。
 *
 * 用两个普通指针 i(s), j(p)，外加两个"存档"变量 starIdx, matchIdx：
 *
 *   i     → 当前在 s 的哪个位置
 *   j     → 当前在 p 的哪个位置
 *   starIdx → 最近一个 * 在 p 中的位置（找不到就是 -1）
 *   matchIdx → s 中与那个 * 的"起点"对应的位置
 *
 * 四个分支，每次只走一个：
 *
 *   ┌─────────────────────────────────────────────────────────┐
 *   │ ① 字符匹配（普通字符相同 || p[j]=='?'）                    │
 *   │    → i++, j++   （双方各走一步，天下太平）                  │
 *   │                                                         │
 *   │ ② p[j] == '*'                                          │
 *   │    → 存档：starIdx=j, matchIdx=i                        │
 *   │    → j++        （先让 * 匹配 0 个字符试试）              │
 *   │                                                         │
 *   │ ③ 走不通了，但之前遇到过 *                                │
 *   │    → 回溯：i = matchIdx + 1，j = starIdx + 1            │
 *   │    → matchIdx = i  （让 * 多吃一个字符）                  │
 *   │                                                         │
 *   │ ④ 以上都不行 → return false                              │
 *   └─────────────────────────────────────────────────────────┘
 *
 * 为什么贪心是对的？
 *   * 吃得越少，留给后面的字符越多 → 容易匹配成功。
 *   所以每次都让 * 先吃最少（0 个），不够再加。
 */

#include <string>
#include <vector>
using namespace std;

// @lc code=start
class Solution {
public:
    bool isMatch(string s, string p) {
        int i = 0, j = 0;           // i 走 s，j 走 p
        int starIdx = -1;           // 最近一个 * 在 p 中的下标
        int matchIdx = 0;           // s 中和那个 * 对齐的位置

        while (i < s.size()) {
            // ---- 分支①：正常匹配（字符相等 或 遇到 ?） ----
            if (j < p.size() && (p[j] == '?' || s[i] == p[j])) {
                ++i;
                ++j;
            }
            // ---- 分支②：遇到 *，先存档，让 * 吃 0 个字符 ----
            else if (j < p.size() && p[j] == '*') {
                starIdx = j;        // 记住 * 在哪
                matchIdx = i;       // 记住 s 的当前位置
                ++j;                // * 先跳过，相当于匹配 0 个字符
            }
            // ---- 分支③：走不通，但之前有 *，回溯让 * 多吃一个 ----
            else if (starIdx != -1) {
                j = starIdx + 1;    // 回到 * 后面的位置
                ++matchIdx;         // 让 * 多吃 s 的一个字符
                i = matchIdx;       // s 从多吃一个后的位置继续
            }
            // ---- 分支④：无计可施 ----
            else {
                return false;
            }
        }

        // s 走完了，p 剩下的必须全部是 *（* 可以匹配空串）
        while (j < p.size() && p[j] == '*') {
            ++j;
        }

        return j == p.size(); // p 也走完了才算完全匹配
    }
};
// @lc code=end
