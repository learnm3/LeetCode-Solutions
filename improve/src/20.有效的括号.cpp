/*
 * @lc app=leetcode.cn id=20 lang=cpp
 *
 * [20] 有效的括号
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】你是游戏客户端程序员，负责开发游戏内置的"脚本编辑器"。
 * 策划可以在脚本中定义嵌套的逻辑块，例如：
 *   { if (血量 < 50%) [使用技能 治疗术] {播放动画 "喝药"} }
 * 编辑器需要在策划保存脚本时，实时检查括号是否匹配——这是语法校验的
 * 第一步。你需要实现一个函数，判断字符串中的三种括号 () [] {} 是否
 * 正确配对且嵌套合法。
 *
 * 【题目】给定一个只包括 '('，')'，'{'，'}'，'['，']' 的字符串 s，
 * 判断字符串是否有效。有效字符串需满足：
 *   1. 左括号必须用相同类型的右括号闭合。
 *   2. 左括号必须以正确的顺序闭合。
 *   3. 每个右括号都有一个对应的相同类型的左括号。
 * 示例:
 *   输入: s = "()"      输出: true
 *   输入: s = "()[]{}"  输出: true
 *   输入: s = "(]"      输出: false
 *   输入: s = "([)]"    输出: false (嵌套顺序不正确)
 *   输入: s = "{[]}"    输出: true
 *
 * ===== 核心思维 =====
 *
 * 这道题是栈（Stack）的教科书级应用。"后进先出"的特性完美匹配
 * 括号的嵌套结构——最后打开的括号必须最先关闭，就像游戏中
 * "后放的 BUFF 先被驱散"。
 *
 * 算法流程像极了"吃豆人"游戏：
 *   遇到左括号 → 压入栈（"记录在案，等配对"）
 *   遇到右括号 → 查看栈顶是不是匹配的左括号
 *     - 是：弹出栈顶（"配对成功，消除"）
 *     - 否：直接返回 false（"配对失败，语法错误"）
 *   遍历完后检查栈是否为空 → 空则全部配对，非空则有括号没闭合
 *
 * 以 "{[]}" 为例：
 *
 *   读到 '{' → 栈: ['{']
 *   读到 '[' → 栈: ['{', '[']
 *   读到 ']' → 栈顶是 '['，匹配！弹出 → 栈: ['{']
 *   读到 '}' → 栈顶是 '{'，匹配！弹出 → 栈: []
 *   遍历结束，栈为空 → true ✓
 *
 * 以 "([)]" 为例：
 *
 *   读到 '(' → 栈: ['(']
 *   读到 '[' → 栈: ['(', '[']
 *   读到 ')' → 栈顶是 '[' ≠ '(' → false ✗
 *
 * 【哈希表映射】用 unordered_map 存储 右括号→左括号 的对应关系，
 * 这样遇到右括号时可以 O(1) 查表找对应的左括号。
 *
 * ===== 代码分步讲解 =====
 *
 * 第1步: 快速剪枝：奇数长度不可能匹配
 * 第2步: 建立右括号→左括号的映射表
 * 第3步: 遍历字符串，遇到左括号压栈
 * 第4步: 遇到右括号，检查栈顶是否匹配
 * 第5步: 最后检查栈是否为空
 *
 * ===== 可迁移模式 =====
 * 【栈匹配模式】适用于：
 *   - HTML/XML 标签匹配（<div> 和 </div>）
 *   - 游戏脚本语法校验（if/endif, loop/endloop）
 *   - 表达式求值（中缀转后缀）
 *   - 撤销/重做操作的栈实现（Undo Stack）
 *   - 迷宫/路径的深度优先搜索
 *   核心：后进先出（LIFO）处理嵌套结构。遇到"开始"压栈，遇到"结束"弹栈配对。
 */

#include <string>
#include <unordered_map>
#include <stack>
using namespace std;

// @lc code=start
class Solution {
public:
    bool isValid(string s) {
        int n = s.size();
        if (n % 2 == 1) return false;                  // 奇数长度肯定不配对

        // 右括号 → 左括号 的映射表
        unordered_map<char, char> pairs = {
            {')', '('}, {']', '['}, {'}', '{'}
        };

        stack<char> stk;
        for (char ch : s) {
            if (pairs.count(ch)) {                     // 是右括号
                if (stk.empty() || stk.top() != pairs[ch]) {
                    return false;                      // 栈顶不匹配或无左括号可配
                }
                stk.pop();
            } else {                                   // 是左括号
                stk.push(ch);
            }
        }

        return stk.empty();                            // 栈为空说明全部配对
    }
};
// @lc code=end
