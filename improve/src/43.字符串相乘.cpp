/*
 * @lc app=leetcode.cn id=43 lang=cpp
 *
 * [43] 字符串相乘
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在开发一款放置类游戏的"超大数系统"（BigNumber）。
 * 玩家金币从个位数一路涨到 10^100 量级，远超 int64 上限。
 * 你需要不依赖任何第三方大数库，手写字符串乘法来支撑
 * 经济系统的数值运算。
 *
 * 类比本题：给定两个用字符串表示的非负整数 num1, num2，
 * 返回它们的乘积（也是字符串）。不能使用 stoi/stoll 等
 * 直接转换，也不能用 __int128。
 *
 * 【与你游戏开发的直接关联】
 * - 伤害公式中两个超大 buff 倍率相乘
 * - 排行榜上两个玩家的资源量比较（先乘某个系数）
 * - 拍卖行中的总价计算（单价 × 数量）
 * - 任何"点击→产出"的指数级增长公式
 *
 * ============================================================
 * 核心思维：逐位相乘 + 累加到结果数组
 * ============================================================
 *
 * 回想你小学手算乘法的过程：
 *
 *       1 2 3
 *   ×     4 5
 *   ---------
 *       6 1 5    ← 123 × 5
 *     4 9 2      ← 123 × 4（左移一位）
 *   ---------
 *     5 5 3 5
 *
 * 你会发现两条规律：
 *
 * 规律1（定位）：
 *   num1 的第 i 位（从右往左数）乘以 num2 的第 j 位，
 *   结果的个位落在 res[i+j] 上，进位累加到 res[i+j-1]。
 *
 *   更准确的下标映射（从低位向高位思考）：
 *   乘积的"低位"部分落在 res[i+j+1]
 *   乘积的"进位"部分落在 res[i+j]
 *
 * 规律2（不进位暂存）：
 *   先把所有位上的乘积"暂存"在数组对应位置，
 *   最后统一处理进位 —— 这样代码只写一遍进位逻辑。
 *
 * 画图演示（num1="123", num2="45"）：
 *
 *   下标:  0   1   2   3   4
 *   res: [ 0,  0,  0,  0,  0 ]   (长度 = len1 + len2 = 5)
 *
 *   i=2('3'), j=1('5'): 3×5=15 → res[3]+=15
 *   i=2('3'), j=0('4'): 3×4=12 → res[2]+=12
 *   i=1('2'), j=1('5'): 2×5=10 → res[2]+=10
 *   i=1('2'), j=0('4'): 2×4=8  → res[1]+=8
 *   i=0('1'), j=1('5'): 1×5=5  → res[1]+=5
 *   i=0('1'), j=0('4'): 1×4=4  → res[0]+=4
 *
 *   累积后: res = [4, 13, 22, 15, 0]
 *
 *   统一进位（从右向左）：
 *   res[4]=0  → 0,  进位0
 *   res[3]=15 → 5,  进位1
 *   res[2]=22+1=23 → 3, 进位2
 *   res[1]=13+2=15 → 5, 进位1
 *   res[0]=4+1=5  → 5, 进位0
 *
 *   最终: [5, 5, 3, 5] → "5535"
 *
 * ============================================================
 * 变体思考（面试官追问方向）
 * ============================================================
 *
 * Q: "如果数字可能有小数点怎么办？"
 * A: 先去掉小数点，记录小数位数，乘完再插回去。
 *
 * Q: "如果要求用科学计数法输出？"
 * A: 大数 = 有效数字 × 10^n，乘法累加指数即可。
 *
 * Q: "如果数字可能是负数？"
 * A: 先处理符号，用绝对值相乘，最后补回符号。
 *
 * Q: "如果我需要给策划展示单位（万/亿/兆）？"
 * A: 这就是大数系统"数值→展示文本"的格式化层——
 *    本质是除法和取余，思路与本解法同源。
 */

#include <string>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    string multiply(string num1, string num2) {
        // 边界：任何数乘 0 都是 0（统一处理，避免最后得到 "000"）
        if (num1 == "0" || num2 == "0") return "0";

        int m = num1.size(), n = num2.size();
        // 两个数相乘，结果最多 m+n 位
        // 用 vector<int> 暂存每一位的累加值
        vector<int> res(m + n, 0);

        // ---- 第一步：逐位相乘并累加到对应位置 ----
        // 从右往左遍历（i 和 j 越小代表越高位）
        for (int i = m - 1; i >= 0; --i) {
            int digit1 = num1[i] - '0';
            for (int j = n - 1; j >= 0; --j) {
                int digit2 = num2[j] - '0';
                // digit1 × digit2 的个位暂存到 res[i+j+1]
                // 十位（进位）暂存到 res[i+j]（下一次统一进位时从这里往上加）
                int sum = digit1 * digit2 + res[i + j + 1];  // 加上之前暂存的值
                res[i + j + 1] = sum % 10;  // 个位留在当前位置
                res[i + j] += sum / 10;     // 进位累加到高位
            }
        }

        // ---- 第二步：将数组转为字符串 ----
        // 跳过前导 0
        int start = 0;
        while (start < res.size() && res[start] == 0) {
            ++start;
        }

        string result;
        for (int i = start; i < res.size(); ++i) {
            result.push_back(res[i] + '0');
        }

        return result;
    }
};
// @lc code=end
