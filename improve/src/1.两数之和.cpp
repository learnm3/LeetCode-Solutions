/*
 * @lc app=leetcode.cn id=1 lang=cpp
 *
 * [1] 两数之和
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你在做"合成配方匹配"系统。
 * 背包里有 N 个材料，每个材料有一个等级。
 * 配方要求：两个材料的等级之和恰好等于目标值。
 * 快速找出任意一对满足条件的材料位置。
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定整数数组 nums 和目标值 target，找出和为 target 的
 * 两个数的下标。假设只有一个答案，且同一元素不能用两次。
 *
 * 示例：nums = [2, 7, 11, 15], target = 9
 *       输出: [0, 1]  （nums[0] + nums[1] = 2 + 7 = 9）
 *
 * ============================================================
 * 核心思维：哈希表存"我需要谁"
 * ============================================================
 *
 * 暴力法：两层循环 O(n²)。
 * 哈希法：一次遍历 O(n)。
 *
 * 遍历每个数 x 时，问自己一个问题：
 *   "target - x 之前出现过吗？"
 *
 * 如果出现过 → 找到了！
 * 如果没出现 → 把 (x, index) 存入哈希表，等后面的人来匹配我。
 *
 * 就像在派对上找人配对：
 *   你进门(2)，需要匹配(7)，看看登记表 → 没有 → 登记自己
 *   他进门(7)，需要匹配(2)，看看登记表 → 有！配对成功
 *
 * 走一遍 [2, 7, 11, 15], target=9：
 *
 *   i=0, x=2: 需要 9-2=7  → 表里没有 7 → 存 map[2]=0
 *   i=1, x=7: 需要 9-7=2  → 表里有 2! → 返回 {0, 1}
 */

// ============================================================
//   C++ 零基础语法讲解（从第一行讲到最后一行的每个符号）
// ============================================================

/*
 * 【#include】
 *   #include 的意思是"把另一个文件的代码粘贴到这里来"。
 *   它用 <尖括号> 括起来表示"从系统标准库目录找这个文件"。
 *   就像游戏里 import 资源包一样。
 *
 *   <vector>     → 引入"动态数组"工具。vector 是可以动态变化大小的数组。
 *                   比如 vector<int> 就是一个装 int 的数组，可以随时往里面加东西。
 *   <unordered_map> → 引入"哈希表"工具。哈希表是一种能 O(1) 快速查找的数据结构。
 *                   就像字典：你给它一个"键"（比如单词），它立刻返回"值"（比如释义）。
 *                   在本题中: 键=数字的值, 值=数字的下标。
 */
#include <vector>
#include <unordered_map>

/*
 * 【using namespace std;】
 *   C++ 标准库里的所有工具（vector, map, string, cout 等）都放在一个叫 "std"
 *   的命名空间里。如果不写这行，每次用 vector 都得写成 std::vector。
 *   写了这一行就可以直接写 vector，省去了 std:: 前缀。
 *
 *   命名空间 = 一个"家族姓氏"，防止不同家族里有同名的工具打架。
 */
using namespace std;

// @lc code=start

/*
 * 【class Solution { ... };】
 *   class = 类 = 一个"蓝图"或"模板"，定义了数据和操作数据的函数。
 *   Solution 是类名（自己起的，LeetCode 规定）。
 *   { } 里面是类的"身体"。
 *   类后面必须有分号 ; 结束。
 *
 *   public: = 公开的。表示下面的东西可以在类外面被访问。
 *     - private: 私有的，只能类内部用（本题没用）
 *     - public: 公开的，谁都能用
 *     - protected: 受保护的，子类能用（等以后继承的时候再学）
 */
class Solution {
public:
    /*
     * 【vector<int> twoSum(vector<int>& nums, int target)】
     *   这是一个"成员函数"（类里面的函数叫成员函数）。
     *
     *   逐段拆解：
     *
     *   vector<int>   → 返回值类型。这个函数返回一个装 int 的 vector。
     *                    （返回两个下标，装在一个 vector 里）
     *
     *   twoSum        → 函数名（自己起的，LeetCode 规定）
     *
     *   ( )           → 括号里是"参数列表"，调用函数时传进来的东西
     *
     *   参数1: vector<int>& nums
     *     vector<int>  → 类型：装 int 的 vector
     *     &            → 引用符号。意思是"借用原数据，不复制一份"。
     *                      如果不加 &，函数内部会复制一份整个数组，浪费内存。
     *                     加了 &，函数直接操作调用者传进来的那一个数组。
     *     nums         → 参数名（自己起的）
     *
     *   参数2: int target
     *     int          → 类型：整数
     *     target       → 参数名（目标值）
     */
    vector<int> twoSum(vector<int>& nums, int target) {

        /*
         * 【unordered_map<int, int> seen;】
         *   声明一个哈希表变量，名字叫 seen（自己起的，= "已见过的数字"）。
         *
         *   逐段拆解：
         *
         *   unordered_map<KeyType, ValueType>  变量名;
         *       ↑              ↑         ↑
         *       键的类型        值的类型    变量名
         *
         *   这里 <int, int> 意思是：
         *     键(key)   = int 类型 → 数字的值（比如 2 或 7）
         *     值(value) = int 类型 → 这个数字在原数组里的下标（比如 0 或 1）
         *
         *   例如把 (nums[0]=2, index=0) 存进去后：
         *     seen[2] = 0    （键=2，值=0）
         *
         *   之后看到数字 7，想查"2 出现过吗？"，只需 seen.count(2)。
         *   这个查询是 O(1) 的，不管哈希表多大，查一次基本不用等。
         */
        unordered_map<int, int> seen;

        /*
         * 【for (int i = 0; i < nums.size(); ++i) { ... }】
         *   for 循环 = 重复执行大括号里的代码。
         *
         *   逐段拆解：
         *
         *   int i = 0;     → ① 初始化：声明一个 int 变量 i，初始值 0。
         *                     i 是"循环变量"，代表当前走到数组的第几个位置。
         *
         *   i < nums.size(); → ② 条件：每次循环前检查。如果为 true 就继续，false 就退出。
         *     nums.size()    → vector 的 size() 函数，返回数组里有多少个元素。
         *                       例：[2,7,11,15] → size() 返回 4。
         *     i < 4          → i 从 0 开始，走到 3，到 4 时 4<4 不成立，循环结束。
         *
         *   ++i            → ③ 每次循环结束后执行：把 i 加 1。
         *                     ++i 等价于 i = i + 1。
         *                     i++ 也是加 1，区别是先加还是先用（这里无所谓）。
         *
         *   循环执行顺序：① → ②(true)→{执行体}→③ → ②(true)→{执行体}→③ → ... → ②(false)→退出
         */
        for (int i = 0; i < (int)nums.size(); ++i) {

            /*
             * 【int need = target - nums[i];】
             *
             *   逐段拆解：
             *   int          → 变量类型：整数
             *   need         → 变量名（= "我需要找的数字"）
             *   =            → 赋值运算符，把右边的值算出来，放进左边的变量
             *   target       → 目标值（函数参数传进来的）
             *   -            → 减法
             *   nums[i]      → 数组 nums 的第 i 个元素。
             *                   [] 是"下标运算符"，nums[0] = 第一个元素 = 2
             *   整体意思：我需要找的数字 = 目标值 - 当前数字
             *   例：target=9, nums[0]=2 → need=7（我需要一个 7 来配对）
             */
            int need = target - nums[i];

            /*
             * 【if (seen.count(need)) { ... }】
             *   if = 条件判断。括号里是 true 就执行大括号里的代码。
             *
             *   seen.count(need)
             *     seen   → 我们之前声明的哈希表
             *     .count(key) → unordered_map 的成员函数。
             *                    检查 key 这个键在不在哈希表里。
             *                    返回值 = 1（存在）或 0（不存在）
             *                    本质上是"出现过几次"，unordered_map 中
             *                    同一个键只能出现一次，所以只可能是 0 或 1。
             *
             *   整体意思：if (哈希表里存在 need 这个键) → 找到了！
             */
            if (seen.count(need)) {

                /*
                 * 【return {seen[need], i};】
                 *
                 *   return → 结束函数，返回后面的值给调用者
                 *
                 *   {seen[need], i}
                 *     {}  → C++11 的"初始化列表"语法。
                 *            自动构造一个 vector<int> 并填入花括号里的元素。
                 *            等价于：
                 *              vector<int> result;
                 *              result.push_back(seen[need]);
                 *              result.push_back(i);
                 *              return result;
                 *            但花括号写法更简洁。
                 *
                 *   seen[need]
                 *     []  → unordered_map 的下标访问运算符。
                 *            用 need 这个键去哈希表里查，返回对应的值。
                 *            例：seen[2] 返回之前存进去的下标 0。
                 *            注意：如果键不存在，[] 会创建一个默认值并插入！
                 *            所以这里先用 .count() 确认存在，再用 [] 取值。
                 *
                 *   i   → 当前的下标（第二个数的位置）
                 *
                 *   整体返回：{之前存的数的下标, 当前数的下标}
                 */
                return {seen[need], i};
            }

            /*
             * 【seen[nums[i]] = i;】
             *   把当前数字和它的下标存进哈希表。
             *
             *   逐段拆解：
             *   seen        → 哈希表
             *   [nums[i]]   → 键 = 当前数字的值（比如 2）
             *   =           → 赋值
             *   i           → 值 = 当前下标（比如 0）
             *
             *   执行结果：seen[2] = 0
             *   意思是"数字 2 在下标 0 出现过"。
             *
             *   为什么要这么做？
             *     后面的人（后面的循环迭代）可能会需要 2 来配对。
             *     到时候他们查 seen.count(2) 就能找到我。
             */
            seen[nums[i]] = i;
        }

        /*
         * 【return {};】
         *   return   → 返回
         *   {}       → 空的初始化列表 = 空的 vector<int>
         *
         *   按题目保证，答案一定存在，所以这行永远不会执行到。
         *   但 C++ 编译器要求你写一个 return，否则会报"控制流可能没有返回值"
         *   的警告。这是给编译器看的"兜底"。
         */
        return {};
    }
};
// @lc code=end
