/*
 * @lc app=leetcode.cn id=11 lang=cpp
 *
 * [11] 盛最多水的容器
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在为开放世界游戏开发"自动地形生成系统"。
 * 程序生成了一个山谷剖面，用高度数组表示。
 * 你需要找出哪两座山之间能蓄最多的雨水，用于确定地图上
 * 最大的天然湖泊位置。
 *
 * 两座山之间能蓄的水量 = 两山距离 × min(左山高, 右山高)。
 * 木桶原理：水的多少取决于较矮的那块木板。
 *
 * 游戏开发中的同样场景：
 * - UI 自适应布局：在固定宽度内放两个面板，求最大可视面积
 * - 技能范围指示器：两个障碍物间能容纳的最大圆形技能范围
 * - 资源采集效率：两个矿点间的连线区域决定采集效率
 * - 碰撞检测优化：AABB 包围盒的最大面积计算
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一个整数数组 height，每个元素代表一条垂直线的高度。
 * 找出两条线，使它们与 x 轴围成的容器能装最多的水。
 *
 * 示例：
 *   输入: [1, 8, 6, 2, 5, 4, 8, 3, 7]
 *   输出: 49
 *   解释: 选择下标 1(高8) 和 8(高7)，宽度 7，min(8,7)=7，
 *         面积 = 7 × 7 = 49
 *
 * ============================================================
 * 核心思维：
 * ============================================================
 *
 * 面积 = 宽度 × 较矮高度（木桶原理：短板决定水位）
 *
 * 双指针从两端开始（此时宽度最大），每次移动较矮的指针。
 * 为什么移动较矮的？因为它是短板——如果不换掉它，
 * 宽度不断缩小的情况下面积不可能变大。
 *
 * 就像两个人在两端往中间走，矮的那个先走，期待遇到更高的。
 */

// ============================================================
//   C++ 零基础语法讲解
// ============================================================

/*
 * 【头文件】
 *   <vector>    → 动态数组
 *   <algorithm> → 算法工具箱（本题用到 min() 和 max()）
 */
#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【int maxArea(vector<int>& height)】
     *
     *   逐段拆解：
     *
     *   int → 返回值类型：整数。返回最大的容器面积。
     *
     *   maxArea → 函数名。max = 最大, Area = 面积。
     *
     *   vector<int>& height → 参数：整数数组的引用。
     *                          height[i] = 第 i 根柱子的高度。
     *                          & 表示借用原数组，不复制。
     */
    int maxArea(vector<int>& height) {

        /*
         * 【int L = 0, R = height.size() - 1;】
         *   声明两个整数变量，用逗号分隔可以一行声明多个同类型变量。
         *
         *   逐段拆解：
         *
         *   int L = 0  → L 是左指针，指向数组最左边（下标 0）
         *
         *   R = height.size() - 1
         *     height.size() → 数组有多少个元素。例：9 个柱子，返回 9。
         *     - 1           → 最后一个元素的下标。例：size=9，最后一个下标是 8。
         *     R             → 右指针，指向数组最右边。
         *
         *   命名惯例：
         *     L = Left（左），R = Right（右）。
         *     你也可以叫 left, right，缩写 L, R 在竞赛中常见。
         */
        int L = 0, R = (int)height.size() - 1;

        /*
         * 【int maxArea = 0;】
         *   记录"迄今为止见到的最大面积"。
         *   初始化为 0（还没计算任何容器）。
         *
         *   这个变量和"最长连续序列"题里的 maxLen 是同一个模式：
         *   先设为最小值，遍历中不断更新。
         */
        int maxArea = 0;

        /*
         * 【while (L < R) { ... }】
         *   while 循环：只要条件为 true 就一直执行循环体。
         *
         *   条件 L < R：左指针在右指针的左边。
         *   当 L == R 或 L > R 时退出（两根指针相遇或交错）。
         *
         *   为什么相遇就停？
         *     容器需要两根不同的柱子。L==R 时只剩一根柱子，
         *     宽度为 0，不能形成容器。所以不需要继续。
         */
        while (L < R) {

            /*
             * 【int area = min(height[L], height[R]) * (R - L);】
             *   计算当前 L 和 R 形成的容器的面积。
             *
             *   逐段拆解：
             *
             *   int area → 声明整数 area（= 面积）
             *
             *   min(height[L], height[R])
             *     min(a, b) → <algorithm> 里的函数，返回 a 和 b 中较小的那个。
             *                  例：min(8, 7) = 7, min(3, 5) = 3
             *
             *     height[L] → 左指针指向的柱子的高度
             *     height[R] → 右指针指向的柱子的高度
             *
             *     为什么取较矮的？木桶原理！
             *       如果左高 8、右高 7，水位只能到 7（水会从矮的那边溢出）。
             *       所以容器的高度 = 较矮柱子的高度。
             *
             *   * → 乘法运算符。面积 = 长 × 宽。
             *       这里：面积 = 较矮高度 × 宽度。
             *
             *   (R - L) → 宽度。R 和 L 之间的距离。
             *             例：R=8, L=1 → 宽度 = 8-1 = 7。
             *             括号是为了改变运算优先级（先算减法）。
             *
             *   完整意思：area = 短板高度 × 两根柱子之间的距离
             */
            int area = min(height[L], height[R]) * (R - L);

            /*
             * 【maxArea = max(maxArea, area);】
             *   如果当前面积比之前记录的都大，就更新记录。
             *
             *   逐段拆解：
             *
             *   maxArea → 全局最大值（要更新的变量）
             *   =       → 赋值
             *   max(maxArea, area)
             *     max(a, b) → 返回 a 和 b 中较大的那个。
             *                  例：max(0, 8) = 8, max(49, 18) = 49
             *
             *   效果：maxArea 始终保持"到目前为止看到的最大面积"。
             */
            maxArea = max(maxArea, area);

            /*
             * 【if (height[L] < height[R]) { ++L; } else { --R; }】
             *   移动较矮的那个指针。
             *
             *   逐段拆解：
             *
             *   if (height[L] < height[R])
             *     比较：左柱子比右柱子矮吗？
             *     是 → 执行 { ++L; }（左指针右移，抛弃矮的左柱）
             *     否 → 执行 { --R; }（右指针左移，抛弃矮的右柱）
             *     相等时走 else（移右指针），其实移哪边都行。
             *
             *   ++L → 自增（前缀）。L = L + 1。（左指针向右走一格）
             *   --R → 自减（前缀）。R = R - 1。（右指针向左走一格）
             *
             *   为什么移动较矮的？
             *     因为矮的那边是短板。宽度已经在缩小（指针往中间靠），
             *     如果不换掉短板，高度上限不变，面积只会越来越小。
             *     换掉短板，虽然宽度减少，但有可能遇到更高的柱子。
             *
             *   一句话：赌一把——换掉矮的，说不定下一个更高。
             */
            if (height[L] < height[R]) {
                ++L;  // 左指针右移
            } else {
                --R;  // 右指针左移
            }
        }

        /*
         * 【return maxArea;】
         *   返回记录的最大面积。
         *   while 循环结束后，maxArea 就是全局最优解。
         */
        return maxArea;
    }
};
// @lc code=end
