/*
 * @lc app=leetcode.cn id=11 lang=cpp
 *
 * [11] 盛最多水的容器
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】开放世界地形中的"最大蓄水盆地"检测
 *
 * 你正在为开放世界游戏开发自动地形生成系统。程序生成了一个山谷剖面，
 * 用高度数组 height[] 表示。你需要找出哪两座山之间的盆地能蓄最多的雨水，
 * 用于确定地图上最大的天然湖泊位置。
 *
 * 两座山之间能蓄的水量 = 两山距离 * min(左山高, 右山高)
 *
 * 例如地形剖面 [1,8,6,2,5,4,8,3,7]：
 *   - 选择第 2 座山(高 8)和第 9 座山(高 7) → 水容量 = (9-2) * min(8,7) = 49
 *   - 这就是能蓄最多水的盆地
 *
 * 游戏开发中的类比场景：
 * - UI 自适应布局：在固定宽度容器内放两个面板，高度由内容决定，求最大面积布局
 * - 技能范围指示器：两个障碍物之间能容纳的最大圆形技能范围
 * - 资源采集效率：两个矿点之间的连线区域决定采集效率
 * - 碰撞检测优化：AABB 包围盒的面积计算
 *
 * 【题目】
 * 给定一个长度为 n 的整数数组 height，有 n 条垂直线，第 i 条线的两个端点
 * 是 (i, 0) 和 (i, height[i])。找出其中的两条线，使得它们与 x 轴共同构成
 * 的容器可以容纳最多的水。返回容器可以储存的最大水量。
 *
 * 示例：
 *   输入: height = [1,8,6,2,5,4,8,3,7]
 *   输出: 49
 *
 *   输入: height = [1,1]
 *   输出: 1
 *
 * ===== 核心思维 =====
 *
 * 一、暴力法的问题
 *
 * 枚举所有 i<j 的组合，计算面积，取最大值。O(n^2) 时间，
 * 在 n=10^5 时需要约 50 亿次计算，不可接受。
 *
 * 二、双指针的贪心策略
 *
 * 关键洞察：面积 = 宽度 * min(左高, 右高)
 *
 * 初始化：左指针 L=0，右指针 R=n-1（此时宽度最大）
 *
 * 每次我们移动较矮的那个指针：
 *   - 为什么移动较矮的？因为面积受限于较矮的那边。
 *     如果移动较高的指针，宽度减少且高度上限不变（甚至可能更矮），面积一定不会增大。
 *     如果移动较矮的指针，虽然宽度减少，但可能遇到更高的线，面积有可能增大。
 *
 * 逐步演示：
 *
 *   [1, 8, 6, 2, 5, 4, 8, 3, 7]
 *    L                         R    面积 = (8-0)*min(1,7) = 8
 *        L                     R    面积 = (8-1)*min(8,7) = 49 ← 最大!
 *        L                  R       面积 = (7-1)*min(8,3) = 18
 *        L               R          面积 = (6-1)*min(8,8) = 40
 *           L            R          面积 = (6-2)*min(6,8) = 24
 *           L         R             面积 = (5-2)*min(6,4) = 12
 *              L      R             面积 = (5-3)*min(2,4) = 4
 *               L     R             面积 = (4-3)*min(5,4) = 4
 *               L  R                L >= R，停止
 *
 * 三、正确性证明（剪枝思想）
 *
 * 每次移动较矮的指针，相当于排除了"以较矮线为一端"的所有剩余组合。
 * 因为对于较矮的线 x，任何以 x 为一端、另一端在 [L+1, R]（或 [L, R-1]）的组合，
 * 其高度 <= x 的高度，宽度小于当前宽度，面积不可能超过当前面积。
 *
 * 四、复杂度分析
 *
 *   - 时间复杂度：O(n)。L 和 R 各移动最多 n 次。
 *   - 空间复杂度：O(1)。
 *
 * 五、可迁移模式 —— 双指针相向而行
 *
 * 双指针相向而行的模式适用于"在有序/半有序结构的两端优化某个目标"：
 *
 *   初始化 L=0, R=n-1
 *   while (L < R) {
 *       计算当前解;
 *       根据"哪边是瓶颈"来决定移动哪边;
 *   }
 *
 * 相关题：
 *   - 15. 三数之和（排序 + 双指针）
 *   - 16. 最接近的三数之和
 *   - 42. 接雨水（双指针从两端，但逻辑不同——算的是总积水而非两个柱子间的面积）
 *   - 167. 两数之和 II（有序数组的双指针）
 *
 * 六、与"接雨水"(#42)的区别
 *
 *   本题：两条线 + 它们之间的宽度 = 矩形面积（木桶效应）
 *   #42：所有柱子之间凹槽能接的雨水总量（每个位置独立计算 min(左边最高,右边最高)-自身高度）
 *
 *   这是完全不同的两个问题，虽然都用双指针，但思路不同。
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int maxArea(vector<int>& height) {
        int L = 0, R = height.size() - 1;
        int maxArea = 0;

        while (L < R) {
            // 当前容器：宽 = R-L, 高 = 较矮的那条线
            int area = min(height[L], height[R]) * (R - L);
            maxArea = max(maxArea, area);

            // 移动较矮的指针：保留较高的那条线，期望在缩小的宽度中找到更高的线
            if (height[L] < height[R]) {
                ++L;
            } else {
                --R;
            }
        }
        return maxArea;
    }
};
// @lc code=end
