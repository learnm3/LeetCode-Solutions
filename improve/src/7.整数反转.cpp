/*
 * @lc app=leetcode.cn id=7 lang=cpp
 *
 * [7] 整数反转
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】倒计时数字的镜面翻转特效
 *
 * 你正在为竞速游戏开发"氮气加速"技能。技能激活时，UI 上显示剩余能量值，
 * 策划要求数字以"镜面翻转"的动画效果出现——即数字在视觉上被反转后显示，
 * 然后再翻转回来。例如能量 123 先显示为 321（镜像），再慢慢转回 123（正常）。
 *
 * 但在实现这个效果时，你需要注意：32 位 int 能存储的值范围是 [-2^31, 2^31-1]，
 * 即 [-2147483648, 2147483647]。如果反转后的值溢出（比如反转 1000000009
 * 得到 9000000001 > 2147483647），则应显示为 0（表示"不可反转"的状态）。
 *
 * 游戏开发中的类比场景：
 * - 分数回放：战斗回放时分数变化需要倒序检查
 * - 校验码生成：对数值取反作为简单校验（如存档完整性校验）
 * - 倒计时显示：倒计时秒数反转作为迷惑性"隐藏计时器"
 *
 * 【题目】
 * 给定一个 32 位有符号整数 x，返回将 x 中的数字部分反转后的结果。
 * 如果反转后整数超过 32 位有符号整数的范围 [-2^31, 2^31-1]，返回 0。
 *
 * 示例：
 *   输入: x = 123    输出: 321
 *   输入: x = -123   输出: -321
 *   输入: x = 120    输出: 21  （去掉前导零）
 *   输入: x = 0      输出: 0
 *
 * ===== 核心思维 =====
 *
 * 一、逐位"弹出-推入"法
 *
 * 核心操作：
 *   1. pop = x % 10    → 弹出 x 的最后一位
 *   2. x /= 10         → x 去掉最后一位
 *   3. rev = rev*10 + pop → 将弹出的位"推入"结果末尾
 *
 * 以 123 为例：
 *
 *   步骤  |  x   |  pop  |  rev
 *   ------+------+-------+------
 *   初始  | 123  |       |  0
 *   1     | 12   |   3   |  0*10+3 = 3
 *   2     | 1    |   2   |  3*10+2 = 32
 *   3     | 0    |   1   | 32*10+1 = 321
 *   结束  | 0    |       |  321
 *
 * 二、溢出检测（难点）
 *
 * 在 rev = rev*10 + pop 之前检查是否会溢出：
 *
 *   正溢出：rev > INT_MAX/10 或 (rev == INT_MAX/10 && pop > 7)
 *   负溢出：rev < INT_MIN/10 或 (rev == INT_MIN/10 && pop < -8)
 *
 * 为什么是 7 和 -8？
 *   INT_MAX = 2147483647 → 最后一位是 7
 *   INT_MIN = -2147483648 → 最后一位是 -8
 *
 * 如果在 rev*10 + pop 之前 rev 已经 > INT_MAX/10，
 * 那么 rev*10 必定 > INT_MAX，无需再看 pop。
 * 如果 rev == INT_MAX/10 = 214748364，rev*10 = 2147483640，
 * 此时 pop 必须 <= 7 才不会溢出。
 *
 * 三、负数取模的 C++ 特性
 *
 * C++ 中 -123 % 10 = -3（向零取整，余数与被除数同号）。
 * 这对我们的算法正好合适——pop 保留了符号，rev = rev*10 + pop 自然处理负数。
 *
 * 四、复杂度分析
 *
 *   - 时间复杂度：O(log10(x))，约等于数字的位数，最多 10 位（32 位 int）。
 *   - 空间复杂度：O(1)。
 *
 * 五、可迁移模式 —— 逐位处理 + 溢出保护
 *
 * 这个模式适用于任何需要逐位操作整数的问题：
 *   - 9. 回文数（反转一半比较）
 *   - 66. 加一（从末位向前进位）
 *   - 258. 各位相加（逐位求和）
 *   - 43. 字符串相乘（逐位乘法）
 */

#include <climits>
using namespace std;

// @lc code=start
class Solution {
public:
    int reverse(int x) {
        int rev = 0;
        while (x != 0) {
            int pop = x % 10; // 弹出末位（负数时 pop 也为负）
            x /= 10;          // 移除末位

            // 正溢出检测：rev > INT_MAX/10 意味着 rev*10 必溢出
            // 或 rev == INT_MAX/10 但 pop > 7（INT_MAX 末位是 7）
            if (rev > INT_MAX / 10 || (rev == INT_MAX / 10 && pop > 7)) return 0;
            // 负溢出检测：同理，INT_MIN 末位是 -8
            if (rev < INT_MIN / 10 || (rev == INT_MIN / 10 && pop < -8)) return 0;

            rev = rev * 10 + pop; // 推入末位
        }
        return rev;
    }
};
// @lc code=end
