/*
 * @lc app=leetcode.cn id=56 lang=cpp
 *
 * [56] 合并区间
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做 BUFF 系统的"时间轴合并"功能。
 * 玩家同时挂了多个 BUFF：攻击药水(0~5秒)、暴击光环(3~8秒)、
 * 加速术(7~10秒)...它们的生效时间有重叠。
 * UI 上的 BUFF 条需要合并显示——重叠的时间段要融合成一条，
 * 不重叠的各自独立。这就是"合并区间"。
 *
 * 游戏开发中同样的"重叠合并"场景：
 * - 伤害判定框：多个 AOE 圈重叠 → 合并成一个大范围
 * - 关卡事件轴：多个触发器时间窗口重叠 → 合并显示
 * - 音频编辑：多段音轨片段有重叠 → 合并成连续波形
 * - 网络包序列：检测丢包区间
 * - 排行榜赛季：跨赛季活动时间段合并
 * - 技能冷却叠加：多个冷却缩减效果的时间线合并
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一组区间 intervals[i] = [start, end]，合并所有重叠的区间，
 * 返回不重叠的区间数组。
 *
 * 示例：
 *   输入: [[1,3], [2,6], [8,10], [15,18]]
 *   输出: [[1,6], [8,10], [15,18]]
 *   （[1,3] 和 [2,6] 重叠 → 合并成 [1,6]）
 *
 * ============================================================
 * 核心思维：排序 + 一次遍历
 * ============================================================
 *
 * 如果区间是按起点排好序的，判断重叠就很简单：
 *
 *   当前区间 cur = [a, b]，下一个区间 next = [c, d]
 *
 *   因为排过序，c >= a 一定成立。
 *   所以重叠的判断退化为：c <= b ?
 *
 *   如果 c <= b → 重叠！cur 的终点拉伸为 max(b, d)
 *   如果 c > b  → 不重叠，cur 进入结果，next 变成新的 cur
 *
 * 图解 [1,3] [2,6] [8,10] [15,18]：
 *
 *   排序后: [1,3] [2,6] [8,10] [15,18]
 *
 *   cur=[1,3], next=[2,6]: 2<=3 → 重叠 → cur=[1, max(3,6)]=[1,6]
 *   cur=[1,6], next=[8,10]: 8>6 → 不重叠 → 输出[1,6], cur=[8,10]
 *   cur=[8,10], next=[15,18]: 15>10 → 不重叠 → 输出[8,10], cur=[15,18]
 *   末尾：输出 [15,18]
 *
 *   结果: [[1,6], [8,10], [15,18]]
 *
 * 就像拼积木：把所有积木按左端对齐排好，一块块往后拼——
 * 碰到重叠的就拉伸，碰到空隙就断开。
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    vector<vector<int>> merge(vector<vector<int>>& intervals) {
        // ① 按起点排序
        sort(intervals.begin(), intervals.end());

        vector<vector<int>> result;
        // ② 拿第一个区间作为"当前正在合并的区间"
        vector<int> cur = intervals[0];

        for (int i = 1; i < intervals.size(); ++i) {
            // ③ 有重叠：拉伸当前区间的终点
            if (intervals[i][0] <= cur[1]) {
                cur[1] = max(cur[1], intervals[i][1]);
            }
            // ④ 无重叠：当前区间确定，开始合并下一个
            else {
                result.push_back(cur);
                cur = intervals[i];
            }
        }
        // ⑤ 别忘了最后一个
        result.push_back(cur);

        return result;
    }
};
// @lc code=end
