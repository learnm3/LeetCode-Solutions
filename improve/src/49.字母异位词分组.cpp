/*
 * @lc app=leetcode.cn id=49 lang=cpp
 *
 * [49] 字母异位词分组
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 聊天敏感词系统又来了（延续第 44 题的场景）。
 * 玩家把 "fuck" 打成 "kufc" 想绕过检测。
 * 你需要把所有"用同一组字母拼出来的词"归到一类，
 * 不管顺序怎么变，都能命中同一个敏感词模式。
 *
 * 另一个典型场景：游戏内置的"字谜/拼词小游戏"。
 * 给你一堆字母乱序的字符串，把所有正确的单词组合
 * 找出来。比如 "eat" "tea" "ate" 都是同一组。
 *
 * 游戏开发中同样的场景：
 * - 物品搜索别名："生命药水" "药水生命" "水生命药" 都搜到同一物品
 * - 玩家起名检测：多个小号用相同字符排列当名字
 * - 成就系统：检测背包里是否有"任意排列的 N 种符文"
 * - 技能组合匹配：装备的符文无论排列顺序，视为同一套装
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 异位词 = 字母完全相同，只是顺序不同的两个字符串。
 * 给一组字符串，把互为异位词的分到同一组。
 *
 * 示例：
 *   输入: ["eat", "tea", "tan", "ate", "nat", "bat"]
 *   输出: [["eat","tea","ate"], ["tan","nat"], ["bat"]]
 *
 * ============================================================
 * 核心思维：给每个字符串算一个"身份证号"
 * ============================================================
 *
 * 异位词的共同点是什么？
 *   排完序之后，它们长得一模一样！
 *
 *   "eat" 排序 → "aet"
 *   "tea" 排序 → "aet"
 *   "ate" 排序 → "aet"
 *
 *   这三个词有相同的"身份证号" = "aet"
 *
 * 所以思路很简单：
 *   ① 对每个单词，算出它的"身份证号"（排序后的字符串）
 *   ② 身份证号相同的，扔进同一组（用哈希表）
 *   ③ 最后把哈希表里所有组倒出来
 *
 * 就像分班：
 *   - 每个学生报自己的生日（排序后的字符串）
 *   - 同一天生日的分到同一个班（hash map key → vector）
 *   - 所有班列出来
 *
 * ============================================================
 * 时空分析
 * ============================================================
 *
 * 时间: O(n × k log k)
 *   n = 字符串数量，k = 最长字符串长度
 *   每个字符串排序需要 k log k
 *
 * 空间: O(n × k)
 *   哈希表存所有字符串
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <string>
#include <unordered_map>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    vector<vector<string>> groupAnagrams(vector<string>& strs) {
        // key = "身份证号"（排序后的字符串）
        // value = 拥有相同身份证号的所有原字符串
        unordered_map<string, vector<string>> groups;

        for (string& s : strs) {
            // ---- ① 算出身份证号 ----
            string key = s;         // 复制一份
            sort(key.begin(), key.end()); // 排序："eat" → "aet"

            // ---- ② 按身份证号分组 ----
            groups[key].push_back(s);  // 把原词扔进对应分组
        }

        // ---- ③ 把所有分组倒出来 ----
        vector<vector<string>> result;
        for (auto& pair : groups) {
            result.push_back(pair.second);  // pair.second 就是那一组的全部词
        }

        return result;
    }
};
// @lc code=end
