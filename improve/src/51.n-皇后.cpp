/*
 * @lc app=leetcode.cn id=51 lang=cpp
 *
 * [51] N 皇后
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做塔防游戏的"防御塔摆放"系统。
 * N×N 的地图上要放 N 座炮塔，要求它们互相不干扰——
 * 任何两座塔不能在同一行、同一列、或同一条斜线上
 * （否则会误伤彼此的供弹线）。
 * 你需要生成所有合法的摆放方案，让策划从中挑选。
 *
 * 游戏开发中同样的"互不冲突的网格放置"逻辑：
 * - 战棋游戏的角色初始站位（不能互相阻挡射界）
 * - 基地建设的建筑布局（同类型建筑不能对齐）
 * - 消除类游戏的宝石生成（初始棋盘无三连）
 * - 关卡编辑器的敌人出生点布置（不重叠、不共线）
 * - 自走棋的棋子摆放（同职业不能共线触发 debuff）
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * N 皇后：在 N×N 棋盘上放 N 个皇后，使它们互不攻击。
 * 皇后攻击范围 = 同行 + 同列 + 同两条对角线。
 * 返回所有可能的棋盘布局。
 *
 * 示例：n=4
 *   输出: [[".Q..",   // 方案1: Q 在 (0,1), (1,3), (2,0), (3,2)
 *           "...Q",
 *           "Q...",
 *           "..Q."],
 *          ["..Q.",   // 方案2: Q 在 (0,2), (1,0), (2,3), (3,1)
 *           "Q...",
 *           "...Q",
 *           ".Q.."]]
 *
 * ============================================================
 * 核心思维：逐行放置 + 三条斜线标记
 * ============================================================
 *
 * 关键洞察：每行只能放一个皇后。
 *   所以问题退化为：对于第 i 行，选哪一列放皇后？
 *
 * 决策树（n=4）：
 *
 *   第0行: [ ] [ ] [ ] [ ]     ← 4 种选择
 *          /   |   |   \
 *   第1行: [x] . . .   ...      ← 去掉冲突列，剩 2~3 种
 *          / \
 *   第2行: .  .  ...            ← 继续去掉冲突
 *        / \
 *   第3行: .  .                 ← 放完 4 个，收货
 *
 * 三条标记数组（关键！）：
 *
 *   col[j]        → 第 j 列是否被占
 *   diag1[i+j]    → 左上→右下对角线（/ 方向）
 *                   规律：同一对角线上 i+j 是常数
 *   diag2[i-j+n-1]→ 右上→左下对角线（\ 方向）
 *                   规律：同一对角线上 i-j 是常数
 *                   加 n-1 是为了把负数偏移成正数
 *
 * 对角线规律图解（n=4）：
 *
 *   左上→右下 (diag1, key=i+j):
 *       0  1  2  3    ← j
 *   0  [0, 1, 2, 3]
 *   1  [1, 2, 3, 4]   每个格子里的数字 = i+j
 *   2  [2, 3, 4, 5]
 *   3  [3, 4, 5, 6]
 *
 *   右上→左下 (diag2, key=i-j+n-1):
 *       0  1  2  3    ← j
 *   0  [3, 2, 1, 0]
 *   1  [4, 3, 2, 1]   每个格子里的数字 = i-j+3
 *   2  [5, 4, 3, 2]
 *   3  [6, 5, 4, 3]
 *
 * 检查冲突变成 O(1)：
 *   if (col[j] || diag1[i+j] || diag2[i-j+n-1]) → 冲突，跳过
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <string>
using namespace std;

// @lc code=start
class Solution {
public:
    vector<vector<string>> solveNQueens(int n) {
        vector<vector<string>> result;
        vector<string> board(n, string(n, '.'));  // 棋盘快照

        vector<bool> col(n, false);               // 列标记
        vector<bool> diag1(2 * n - 1, false);     // 左上→右下对角线 (i+j)
        vector<bool> diag2(2 * n - 1, false);     // 右上→左下对角线 (i-j+n-1)

        backtrack(0, n, board, col, diag1, diag2, result);
        return result;
    }

private:
    void backtrack(int row, int n, vector<string>& board,
                   vector<bool>& col, vector<bool>& diag1,
                   vector<bool>& diag2, vector<vector<string>>& result) {
        // 所有行都放完了 → 收集结果
        if (row == n) {
            result.push_back(board);
            return;
        }

        // 在当前行尝试每一列
        for (int j = 0; j < n; ++j) {
            int d1 = row + j;          // 左斜线编号
            int d2 = row - j + n - 1;  // 右斜线编号

            // O(1) 检查冲突
            if (col[j] || diag1[d1] || diag2[d2]) continue;

            // 做选择
            board[row][j] = 'Q';
            col[j] = diag1[d1] = diag2[d2] = true;

            // 递归下一行
            backtrack(row + 1, n, board, col, diag1, diag2, result);

            // 撤销选择
            board[row][j] = '.';
            col[j] = diag1[d1] = diag2[d2] = false;
        }
    }
};
// @lc code=end
