/*
 * @lc app=leetcode.cn id=13 lang=cpp
 *
 * [13] 罗马数字转整数
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】你是游戏客户端程序员，正在开发一个装备属性解析系统。策划配置表里，
 * 装备的稀有度等级用罗马数字标注（I=普通, V=稀有, X=史诗, L=传说...）。
 * 你需要写一个函数，把罗马数字字符串快速转换成程序内部使用的整数，以便
 * 进行稀有度比较、排序和掉落概率计算。这个函数在加载配置表时被大量调用，
 * 必须高效可靠。
 *
 * 【题目】给定一个罗马数字字符串 s，将其转换为整数。
 * 罗马数字规则：
 *   I=1, V=5, X=10, L=50, C=100, D=500, M=1000
 *   通常情况下，小数字在大数字右边表示加法（VI = 5+1 = 6）
 *   小数字在大数字左边表示减法（IV = 5-1 = 4）
 * 示例:
 *   输入: s = "III"    输出: 3
 *   输入: s = "IV"     输出: 4
 *   输入: s = "IX"     输出: 9
 *   输入: s = "LVIII"  输出: 58  (L=50, V=5, III=3)
 *   输入: s = "MCMXCIV" 输出: 1994 (M=1000, CM=900, XC=90, IV=4)
 *
 * ===== 核心思维 =====
 *
 * 这道题的核心洞察非常巧妙：与其费力判断"当前位置是加还是减"，
 * 不如用一个统一规则 —— 从左到右遍历，比较当前字符和下一个字符的值：
 *
 *   如果 当前值 < 下一个值  → 减去当前值（如 IV 中 I=1 < V=5，所以 -1）
 *   如果 当前值 >= 下一个值 → 加上当前值（如 VI 中 V=5 > I=1，所以 +5）
 *   最后一个字符没有"下一个"，直接加上。
 *
 * 用例子走一遍 "MCMXCIV"：
 *
 *   字符:  M    C    M    X    C    I    V
 *   数值: 1000  100 1000  10  100   1    5
 *   比较: M>C?  C<M?  M>X?  X<C?  C>I?  I<V?  末尾
 *         是    是    是    是    是    是
 *   操作: +1000 -100 +1000  -10 +100   -1   +5
 *   累计: 1000 → 900 → 1900 → 1890 → 1990 → 1989 → 1994 ✓
 *
 * 就像游戏里解析"减益效果描述"：遇到"攻击力-10%"要知道是减，
 * 遇到"攻击力+10%"要知道是加。这里的"减"信号就是"小数字在大数字前面"。
 *
 * "小在前是减，大在前是加，最后一位直接加" —— 记住这句就够了。
 *
 * ===== 代码分步讲解 =====
 *
 * 第1步: 建立符号到数值的映射表（类似游戏里的查表转换）
 * 第2步: 初始化总和为 0
 * 第3步: 遍历每个字符，获取其数值
 * 第4步: 比较当前值与下一个值，决定加或减
 * 第5步: 返回最终总和
 *
 * ===== 可迁移模式 =====
 * 【查表法 + 相邻比较】这种模式在很多场景都会出现：
 *   - 解析自定义标记语言（如游戏脚本中 ABC 表示不同指令）
 *   - 处理带有"修饰符"的数值序列（温度单位、货币符号）
 *   - 编码解码问题（如短链接的 62 进制转换）
 *   核心思想：用一个 O(1) 的查找表替代复杂的 if-else 分支。
 */

#include <string>
#include <unordered_map>
using namespace std;

// @lc code=start
class Solution {
public:
    int romanToInt(string s) {
        // 符号映射表 —— 就像游戏引擎里的枚举查表
        unordered_map<char, int> symbol = {
            {'I', 1}, {'V', 5}, {'X', 10}, {'L', 50},
            {'C', 100}, {'D', 500}, {'M', 1000}
        };

        int total = 0;
        int n = s.size();

        for (int i = 0; i < n; ++i) {
            int cur = symbol[s[i]];
            // 核心规则：当前值 < 下一值 → 减法，否则 → 加法
            if (i + 1 < n && cur < symbol[s[i + 1]]) {
                total -= cur;
            } else {
                total += cur;
            }
        }

        return total;
    }
};
// @lc code=end
