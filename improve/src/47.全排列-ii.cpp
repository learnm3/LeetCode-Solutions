/*
 * @lc app=leetcode.cn id=47 lang=cpp
 *
 * [47] 全排列 II
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 上一题（46）你的技能连招求解器跑通了。
 * 但现在策划新增了一个设定：有两个相同属性的技能（比如
 * 火球A 和 火球B 都是火系），它们功能完全一样，但名称不同。
 * 此时 [火A, 冰, 火B] 和 [火B, 冰, 火A] 对伤害计算来说
 * 是等价的——你需要去重，避免重复计算。
 *
 * 游戏开发中的去重排列场景：
 * - 背包里有多个相同的药水，排列时视为等价
 * - 装备镶嵌：3 颗同色宝石，排列结果去重
 * - 技能符文页：同一种符文塞在多个槽位，顺序可能重复
 * - 合成配方：相同原料的不同摆放视为同一种配方
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * nums 可能包含重复数字，返回所有不重复的排列。
 *
 * 示例：nums = [1, 1, 2]
 * 输出: [[1,1,2], [1,2,1], [2,1,1]]
 *
 * 注意：只有 3 种，而不是 6 种（两个 1 互换不算新排列）
 *
 * ============================================================
 * 核心思维：在同一层决策树中，相同数字只能用一次
 * ============================================================
 *
 * 先看"不去重"会产生什么冗余：
 *
 *               []
 *        /      |      \
 *      1a       1b      2        ← 选第1个数
 *     / \      / \     / \
 *    1b  2    1a  2   1a 1b      ← 选第2个数
 *    |   |    |   |    |  |
 *    2   1b   2   1a   1b 1a      ← 选第3个数
 *
 *   → 结果: [1a,1b,2], [1a,2,1b], [1b,1a,2], [1b,2,1a], ...
 *   但 1a 和 1b 本质是同一个值！[1a,1b,2] 和 [1b,1a,2] 重复了。
 *
 * 观察重复发生在哪：
 *   同一层中，如果你刚刚处理过一个 1，又遇到另一个 1，
 *   此时再往下搜，生成的排列必定是重复的。
 *
 * 一句话去重策略：
 *   「排序后，在同一层决策树中，如果当前数字和上一个数字相同，
 *     且上一个数字刚被撤销（!used[i-1]），就跳过。」
 *
 * ============================================================
 * !used[i-1] 到底是什么意思？—— 最关键的面试点
 * ============================================================
 *
 * 用 [1a, 1b, 2]（排序后）画图：
 *
 *   情况A: used[i-1]==true
 *     → 上一个相同的数字在"祖先路径"中被选中了
 *     → 我们正处在父子关系中（纵向）
 *     → 允许！[1a, 1b, ...] 是合法的新路径。
 *
 *   情况B: used[i-1]==false
 *     → 上一个相同的数字在同一层刚被"撤销"了
 *     → 我们正处在兄弟关系中（横向）
 *     → 禁止！如果选了当前数字，会和刚处理完的那个分支产生重复。
 *
 * 实际执行 [1a, 1b, 2]（排序后）：
 *
 *   i=0(1a): used[0]=T, 递归深入
 *     i=1(1b): used[0]==T → 纵向，合法！继续 → 得 [1a,1b,2]
 *     撤销 1b (used[1]=F)
 *     i=2(2): 正常选 → 得 [1a,2,1b]
 *     撤销 2
 *   撤销 1a (used[0]=F)
 *
 *   i=1(1b): nums[1]==nums[0] && used[0]==F → 横向重复！跳过！
 *
 *   i=2(2): 选 2 → 递归深入
 *     i=0(1a): 正常选 → 递归深入
 *       i=1(1b): used[0]==T → 纵向合法！得 [2,1a,1b]
 *
 *   最终: [[1a,1b,2], [1a,2,1b], [2,1a,1b]] → 恰好 3 个，无重复。
 *
 * ============================================================
 * 和上一题（46）的唯一区别
 * ============================================================
 *
 * 46 的代码 + 两处改动 = 47：
 *
 *   ① 开头加一行 sort(nums.begin(), nums.end());
 *   ② for 循环里加一行去重判断
 *
 *   if (i > 0 && nums[i] == nums[i-1] && !used[i-1]) continue;
 *                                       ~~~~~~~~~~~~
 *                                       这一小段是灵魂
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    vector<vector<int>> permuteUnique(vector<int>& nums) {
        sort(nums.begin(), nums.end());  // ① 先排序，让相同数字紧挨着
        vector<vector<int>> result;
        vector<int> path;
        vector<bool> used(nums.size(), false);
        backtrack(nums, used, path, result);
        return result;
    }

private:
    void backtrack(vector<int>& nums, vector<bool>& used,
                   vector<int>& path, vector<vector<int>>& result) {
        if (path.size() == nums.size()) {
            result.push_back(path);
            return;
        }

        for (int i = 0; i < nums.size(); ++i) {
            if (used[i]) continue;

            // ② 去重核心：同一层兄弟节点中，相同数字只走第一个
            if (i > 0 && nums[i] == nums[i-1] && !used[i-1]) continue;

            used[i] = true;
            path.push_back(nums[i]);

            backtrack(nums, used, path, result);

            path.pop_back();
            used[i] = false;
        }
    }
};
// @lc code=end
