/*
 * @lc app=leetcode.cn id=53 lang=cpp
 *
 * [53] 最大子数组和
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做动作游戏的"DPS 峰值分析"工具。
 * 战斗日志记录了过去 N 秒内每秒的伤害输出：
 *   [3, -4, 2, 7, -8, 5, -1, 3]
 * 正值 = 命中伤害，负值 = 被格挡/未命中。
 * 你需要找出"连续哪几秒的总伤害最高"——这就是"最大子数组和"。
 *
 * 游戏开发中同样的"连续区间最值"场景：
 * - 帧率分析：找出掉帧最严重的一段连续时间
 * - 经济曲线：找出金币增长最快的一段连续时段
 * - 网络延迟：找出延迟最高的突发窗口
 * - 玩家在线峰值：找出连续在线人数最多的时间段
 * - 性能 Profiler：找出 CPU 占用最高的一段连续帧
 * - 连击系统：找出连续击杀数最高的那段战斗
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定整数数组 nums，找出具有最大和的连续子数组，返回其和。
 *
 * 示例：
 *   输入: [-2, 1, -3, 4, -1, 2, 1, -5, 4]
 *   输出: 6  （子数组 [4, -1, 2, 1] 的和）
 *
 * ============================================================
 * 核心思维：Kadane 算法（只关心"当前"和"历史最佳"）
 * ============================================================
 *
 * 暴力做法：枚举所有子数组，O(n²)。
 * 聪明做法：一次遍历，O(n)。
 *
 * 核心问题：走到 nums[i] 时，要不要把它拼到前面的子数组里？
 *
 * 决策规则（就一条）：
 *   "如果前面的和是负数，带上它只会拖累我，不如我自己单干。"
 *
 * 用代码说就是：
 *   curSum = max(nums[i], curSum + nums[i])
 *            |              |
 *            └── 前面是负的，   └── 前面是正的，
 *               从头开始        拼上去
 *
 * 走一遍 [-2, 1, -3, 4, -1, 2, 1, -5, 4]：
 *
 *   i=0: curSum = max(-2, 0+-2) = -2,  maxSum = -2
 *   i=1: curSum = max(1, -2+1) = 1,    maxSum = 1
 *        ↑ 前面是负的，抛弃，从 1 重新开始
 *
 *   i=2: curSum = max(-3, 1-3) = -2,   maxSum = 1
 *   i=3: curSum = max(4, -2+4) = 4,    maxSum = 4
 *        ↑ 前面是负的，抛弃，从 4 重新开始
 *
 *   i=4: curSum = max(-1, 4-1) = 3,    maxSum = 4
 *   i=5: curSum = max(2, 3+2) = 5,     maxSum = 5
 *   i=6: curSum = max(1, 5+1) = 6,     maxSum = 6 ★
 *   i=7: curSum = max(-5, 6-5) = 1,    maxSum = 6
 *   i=8: curSum = max(4, 1+4) = 5,     maxSum = 6
 *
 *   答案: 6
 *
 * 就像挑队友：下一个来的是战斗力，前面队伍的总战力如果是负数，
 * 你还带着就是减分项，不如不带。
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int maxSubArray(vector<int>& nums) {
        int curSum = nums[0];   // 以当前位置结尾的最大子数组和
        int maxSum = nums[0];   // 全局最大值（历史最佳）

        for (int i = 1; i < nums.size(); ++i) {
            // 决策：前面是包袱就扔掉，是助力就带上
            curSum = max(nums[i], curSum + nums[i]);
            // 更新全局最佳
            maxSum = max(maxSum, curSum);
        }

        return maxSum;
    }
};
// @lc code=end
