/*
 * @lc app=leetcode.cn id=26 lang=cpp
 *
 * [26] 删除有序数组中的重复项
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】你在开发一个 RPG 游戏的 Buff 状态栏。
 * 玩家身上的 Buff/Debuff 图标按添加时间排序存储在一个数组中。
 * 但某些 Buff 可能被"刷新"机制重复添加（例如同一件装备的被动效果重复触发），
 * 导致同类型的 Buff 出现多次。UI 要求每种 Buff 只显示一个图标，
 * 你需要"原地去重"：在数组中保留每种 Buff 的第一个出现，移除后续重复项，
 * 并返回去重后的 Buff 数量。这就是"删除有序数组中的重复项"问题。
 *
 * 另一个情境：聊天系统中合并连续相同发送者的消息（折叠刷屏消息），
 * 保留每个发送者的第一条消息。
 *
 * 【题目】给定一个升序数组 nums，原地删除重复元素，使每个元素只出现一次，
 * 返回去重后数组的新长度。必须在原数组上操作，不能使用额外数组空间。
 * 示例：
 *   输入：nums = [1,1,2]
 *   输出：2, nums = [1,2,_]
 *   输入：nums = [0,0,1,1,1,2,2,3,3,4]
 *   输出：5, nums = [0,1,2,3,4,_,_,_,_,_]
 *
 * ===== 核心思维 =====
 *
 * 双指针（快慢指针）——"搬运"模型：
 *
 * 想象你有一排箱子，有些是重复的。你要把"不重复"的箱子搬到前面。
 *
 * 慢指针 slow：指向"已整理好的区域"的最后一个位置（也即下一个要放置的位置）
 * 快指针 fast：扫描整个数组，寻找"新面孔"
 *
 * 初始：slow = 0（第一个元素永远不重复）
 * fast 从 1 开始扫描：
 *   - 如果 nums[fast] != nums[slow]：发现新元素
 *     slow++，然后把 fast 位置的元素"搬"到 slow 位置
 *   - 如果 nums[fast] == nums[slow]：还是同一个元素，跳过
 *
 * 最后 slow + 1 就是去重后的长度。
 *
 * 图解（nums = [1,1,2,2,3]）：
 *   初始：slow=0, fast=1
 *   [1, 1, 2, 2, 3]
 *    s  f
 *   nums[1]==nums[0]，跳过
 *
 *   [1, 1, 2, 2, 3]
 *    s     f
 *   nums[2]!=nums[0]，slow++，nums[1]=2
 *   [1, 2, 2, 2, 3]
 *       s  f
 *
 *   nums[3]==nums[1]，跳过
 *   [1, 2, 2, 2, 3]
 *       s     f
 *   nums[4]!=nums[1]，slow++，nums[2]=3
 *   [1, 2, 3, 2, 3]
 *          s     f
 *
 *   结果：长度 3，前面是 [1,2,3]
 *
 * ===== 可迁移的解题模式 =====
 *
 * "双指针原地修改数组"模式：
 *   - 慢指针维护"已处理区域"的边界
 *   - 快指针扫描未处理区域
 *   - 满足条件时，快指针的值搬运到慢指针位置
 *
 * 同类问题：
 *   - 移除元素（保留不等于某值的元素）
 *   - 移动零（将零移到数组末尾）
 *   - 游戏中 Buff 列表去重（保留每种 Buff 的最新状态或首个状态）
 *   - 子弹对象池中去除已经销毁的子弹
 *   - 音游判定结果列表中合并连续的 Perfect/Great
 */

#include <vector>
using namespace std;

// @lc code=start
class Solution {
public:
    int removeDuplicates(vector<int>& nums) {
        int n = nums.size();
        if (n == 0) return 0;

        int slow = 0; // 已去重区域的末尾索引

        // fast 扫描整个数组，发现新元素就搬到 slow+1 位置
        for (int fast = 1; fast < n; fast++) {
            if (nums[fast] != nums[slow]) {
                slow++;
                nums[slow] = nums[fast];
            }
        }

        return slow + 1; // 去重后的长度
    }
};
// @lc code=end
