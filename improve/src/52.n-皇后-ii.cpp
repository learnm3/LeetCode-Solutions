#include <vector>
#include <functional>
using namespace std;

// @lc code=start
class Solution {
public:
    int totalNQueens(int n) {
        int count = 0;  // 只计数，不存棋盘

        vector<bool> col(n, false);
        vector<bool> diag1(2 * n - 1, false);
        vector<bool> diag2(2 * n - 1, false);

        // 直接用 lambda 递归，代码全部内聚
        function<void(int)> backtrack = [&](int row) {
            if (row == n) {
                ++count;  // 找到一种合法方案，计数+1（51题这里是存棋盘）
                return;
            }
            for (int j = 0; j < n; ++j) {
                int d1 = row + j;
                int d2 = row - j + n - 1;
                if (col[j] || diag1[d1] || diag2[d2]) continue;

                col[j] = diag1[d1] = diag2[d2] = true;
                backtrack(row + 1);
                col[j] = diag1[d1] = diag2[d2] = false;
            }
        };

        backtrack(0);
        return count;
    }
};
// @lc code=end
