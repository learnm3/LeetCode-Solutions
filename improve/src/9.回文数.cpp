/*
 * @lc app=leetcode.cn id=9 lang=cpp
 *
 * [9] 回文数
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】关卡编号的"镜像关卡"检测
 *
 * 你正在为平台跳跃游戏设计关卡选择界面。策划提出一个彩蛋需求：
 * 如果关卡编号本身是回文数（如 121、1331），则解锁一个"镜像关卡"——
 * 该关卡的地图是原关卡的左右翻转版本。例如关卡 121 是回文数，
 * 玩家可以进入"镜像世界 121"，所有平台、敌人位置都左右对称翻转。
 *
 * 你需要写一个函数快速判断任意关卡编号（int）是否是回文数。
 * 限制：不能把整数转换为字符串（因为要处理数百万个关卡编号，
 * 字符串转换的额外开销不可忽略）。
 *
 * 游戏开发中的类比场景：
 * - 成就系统：判断玩家击杀数的"回文时刻"（如 12321 杀），触发特殊成就
 * - 伤害数值美化：暴击伤害如果是回文数，显示特殊粒子特效
 * - 经验值里程碑：等级经验值刚好是回文数时弹窗庆祝
 * - 倒计时：倒数到回文秒数（如 32123）时触发音效提示
 *
 * 【题目】
 * 给定一个整数 x，如果 x 是一个回文整数，返回 true；否则返回 false。
 * 回文数是指正序和倒序读都是一样的整数。
 * 进阶：不将整数转为字符串来解决这个问题。
 *
 * 示例：
 *   输入: x = 121    输出: true
 *   输入: x = -121   输出: false  （负号导致不对称）
 *   输入: x = 10     输出: false  （倒序是 01）
 *   输入: x = 0      输出: true
 *
 * ===== 核心思维 =====
 *
 * 一、排除明显不是回文的情况
 *
 *   1. 负数一定不是回文（-121 != 121-）
 *   2. 末位是 0 的正数，只有 0 本身是回文（10 → 01 不是）
 *
 * 二、反转一半数字（关键优化）
 *
 * 不需要反转整个数字，只需要翻转后半部分，与前半部分比较：
 *
 *   原数 x = 1221
 *
 *   步骤  |  x    | reversed |  说明
 *   ------+-------+----------+-------------------
 *   初始  | 1221  |     0    |
 *   1     | 122   |     1    | reversed = 0*10 + (1221%10) = 1
 *   2     | 12    |    12    | reversed = 1*10 + (122%10) = 12
 *   停止  | 12    |    12    | x(12) <= reversed(12) → 退出
 *
 *   结果：x == reversed → 12 == 12 → 是回文！
 *
 * 对于奇数位回文如 12321：
 *
 *   步骤  |  x    | reversed |
 *   ------+-------+----------+
 *   初始  | 12321 |     0    |
 *   1     | 1232  |     1    |
 *   2     | 123   |    12    |
 *   3     | 12    |   123    |  x(12) <= reversed(123) → 退出
 *
 *   结果：x == reversed/10 → 12 == 123/10 = 12 → 是回文!
 *   （中间的数字 3 不影响对称性）
 *
 * 三、为什么"反转一半"更好？
 *
 *   1. 时间复杂度不变（O(log10 n)），但常数减半
 *   2. 避免了溢出风险——反转整个 2147483647 会溢出，
 *      但只反转一半，reversed 最多和 x 位数一致，不会溢出
 *   3. 比转字符串更直观地体现"不进位操作"的思维
 *
 * 四、复杂度分析
 *
 *   - 时间复杂度：O(log10(x))，约数字位数的一半（最多 5 次迭代）。
 *   - 空间复杂度：O(1)。
 *
 * 五、可迁移模式 —— 双指针思想在数字上的应用
 *
 * 回文问题本质是对称性检查，"反转一半"相当于让右指针从末尾向中间移动。
 * 这个思路的泛化：
 *   - 判断链表是否回文：快慢指针找中点 + 反转后半段
 *   - 判断数组是否回文：双指针从两端向中间
 *   - 生成下一个回文数：找到中点，加一后镜像拷贝
 */

#include <climits>
using namespace std;

// @lc code=start
class Solution {
public:
    bool isPalindrome(int x) {
        // 负数一定不是回文；末位为 0 的正数（除 0 外）也不是回文
        if (x < 0 || (x % 10 == 0 && x != 0)) {
            return false;
        }

        int reversed = 0;
        // 只反转后半部分：当 x <= reversed 时说明已处理过半
        while (x > reversed) {
            reversed = reversed * 10 + x % 10; // 将 x 的末位"推入" reversed
            x /= 10;                            // x 去掉末位
        }

        // 偶数位：x == reversed
        // 奇数位：x == reversed / 10（去掉中间那位）
        return x == reversed || x == reversed / 10;
    }
};
// @lc code=end
