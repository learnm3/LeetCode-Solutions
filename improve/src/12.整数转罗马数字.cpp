/*
 * @lc app=leetcode.cn id=12 lang=cpp
 *
 * [12] 整数转罗马数字
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】装备强化等级的罗马数字显示
 *
 * 你正在为奇幻 RPG 游戏开发装备强化系统。策划要求装备的强化等级使用
 * 罗马数字显示，以营造"古代遗迹"的氛围感。例如 +1 显示为 "+I"，
 * +5 显示为 "+V"，+2024 显示为 "+MMXXIV"。
 *
 * 玩家在锻造界面可以看到当前装备的强化等级，这个数字需要实时转换为
 * 罗马数字字符串。你需要实现一个高效的转换函数。
 *
 * 罗马数字由 7 个基本符号组成：
 *   I=1, V=5, X=10, L=50, C=100, D=500, M=1000
 *
 * 特殊规则（减法表示）：
 *   I 可以放在 V (5) 和 X (10) 前面表示 4 和 9
 *   X 可以放在 L (50) 和 C (100) 前面表示 40 和 90
 *   C 可以放在 D (500) 和 M (1000) 前面表示 400 和 900
 *
 * 游戏开发中的类比场景：
 * - 关卡编号：用罗马数字标注章节（Chapter I, II, III, IV...）
 * - 排行榜：白银 I, 白银 II, ..., 黄金 I...（段位系统）
 * - 装备等级：传说 I, 传说 II, ..., 传说 X
 * - 成就等级：用罗马数字表示成就的星级
 *
 * 【题目】
 * 给定一个整数 num（1 <= num <= 3999），将其转换为罗马数字字符串。
 *
 * 示例：
 *   输入: 3     输出: "III"
 *   输入: 4     输出: "IV"
 *   输入: 9     输出: "IX"
 *   输入: 58    输出: "LVIII"    （L=50, V=5, III=3）
 *   输入: 1994  输出: "MCMXCIV"  （M=1000, CM=900, XC=90, IV=4）
 *
 * ===== 核心思维 =====
 *
 * 一、贪心策略：从大到小"尽可能多"地使用符号
 *
 * 罗马数字的本质是用固定值的符号组合来表示数字，且符号值从大到小排列。
 * 因此一个自然的思路是：每次选择能用的最大符号，尽可能多地使用它，
 * 然后减去相应值，继续处理剩余部分。
 *
 * 这就像找零钱：用面额最大的钞票先找，再用次大的...
 *
 * 二、包含减法组合的映射表
 *
 * 把 13 个"面额"（包括减法组合）都列出来：
 *
 *   值:   1000  900  500  400  100  90   50   40   10   9    5    4    1
 *   符号:  M    CM   D    CD   C   XC   L   XL   X   IX   V   IV   I
 *
 * 注意：面额必须是降序排列，这样才能保证贪心正确。
 *
 * 三、转换过程演示 (num = 1994)
 *
 *   步骤  |  剩余值  |  当前操作              |  结果累计
 *   ------+----------+------------------------+-----------
 *   1     |  1994    |  1000 ≤ 1994, 用 M    |  "M"     剩余: 994
 *   2     |  994     |  900 ≤ 994, 用 CM     |  "MCM"   剩余: 94
 *   3     |  94      |  90 ≤ 94, 用 XC       |  "MCMXC" 剩余: 4
 *   4     |  4       |  4 ≤ 4, 用 IV         |  "MCMXCIV" 剩余: 0
 *   5     |  0       |  剩余 0，结束          |  "MCMXCIV"
 *
 * 四、贪心法的正确性
 *
 * 为什么贪心法对罗马数字一定正确？
 * 因为罗马数字的面额系统具有"规范形式"——任意数字的罗马表示中，
 * 同一个符号最多连续出现 3 次（如 III=3, XXX=30），
 * 而减法组合（IV, IX, XL, XC, CD, CM）恰好填补了 4 次连续符号的空白。
 * 这保证了从大到小的贪心选择总是能得到最简表示。
 *
 * 五、复杂度分析
 *
 *   - 时间复杂度：O(1)。面额表固定 13 项，while 循环总次数由输入决定
 *     （最坏情况下 num=3999，需要 MMM + CM + XC + IX ≈ 3+1+1+1+... 约 15 次迭代）。
 *   - 空间复杂度：O(1)。结果字符串长度固定（最大 3999 = "MMMCMXCIX"，15 字符）。
 *
 * 六、可迁移模式 —— 贪心 + 查表法
 *
 * 这个模式的核心是：建立"面额 → 符号"的降序映射表，然后贪心削减。
 * 适用于任何"用有限符号组合表示数值"的场景：
 *
 *   - 数字转中文大写（1234 → "一千二百三十四"）
 *   - 数字转英文单词（123 → "One Hundred Twenty Three"）
 *   - 货币面额兑换（ATM 出钞：优先给大面额钞票）
 *   - 经验值转等级（固定经验表，从高到低匹配）
 *
 * 通用模板：
 *   for (auto [value, symbol] : 降序映射表) {
 *       while (num >= value) {
 *           result += symbol;
 *           num -= value;
 *       }
 *   }
 */

#include <string>
using namespace std;

// @lc code=start

// 映射表必须按面额降序排列，这是贪心法正确性的保证
const pair<int, string> valueSymbols[] = {
    {1000, "M"},
    {900,  "CM"},
    {500,  "D"},
    {400,  "CD"},
    {100,  "C"},
    {90,   "XC"},
    {50,   "L"},
    {40,   "XL"},
    {10,   "X"},
    {9,    "IX"},
    {5,    "V"},
    {4,    "IV"},
    {1,    "I"},
};

class Solution {
public:
    string intToRoman(int num) {
        string roman;
        // 贪心：从大到小尝试每个面额
        for (const auto& [value, symbol] : valueSymbols) {
            // 在当前面额下，能塞多少塞多少
            while (num >= value) {
                roman += symbol;
                num -= value;
            }
            // 提前终止优化（可选）
            if (num == 0) break;
        }
        return roman;
    }
};
// @lc code=end
