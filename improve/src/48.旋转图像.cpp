/*
 * @lc app=leetcode.cn id=48 lang=cpp
 *
 * [48] 旋转图像
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做背包系统的"物品旋转"功能。
 * 每个物品是一个 N×N 的图标矩阵（像素数组），玩家右键
 * 可以旋转 90°。要求原地旋转，不能新建一个矩阵（内存紧
 * 张，背包里可能有几百个图标同时显示）。
 *
 * 游戏开发中同样的"矩阵原地旋转"逻辑还用在：
 * - 小地图/MiniMap 的方向变化（N 朝上 → E 朝上）
 * - 俄罗斯方块/Tetris 的方块旋转
 * - 关卡编辑器中 90° 旋转一块地砖网格
 * - 角色纸娃娃系统的装备图标旋转
 * - 战棋游戏的棋盘视角切换
 * - 纹理/精灵的运行时旋转（SpriteBatch 之前）
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一个 N×N 矩阵，原地顺时针旋转 90°。
 *
 * 示例：
 *   输入:  [1,2,3]      输出: [7,4,1]
 *          [4,5,6]      →     [8,5,2]
 *          [7,8,9]            [9,6,3]
 *
 * ============================================================
 * 核心思维：两步走 = 转置 + 水平翻转
 * ============================================================
 *
 * 顺时针旋转 90° 等价于两个简单操作的组合：
 *
 *   ① 转置（沿主对角线翻折）：matrix[i][j] ↔ matrix[j][i]
 *   ② 水平翻转（每行左右颠倒）：每行的首尾交换
 *
 * 为什么？画个图：
 *
 *   原矩阵             ① 转置后           ② 每行翻转后
 *   [1, 2, 3]        [1, 4, 7]          [7, 4, 1]
 *   [4, 5, 6]   →    [2, 5, 8]    →     [8, 5, 2]
 *   [7, 8, 9]        [3, 6, 9]          [9, 6, 3]
 *                        ↑                  ↑
 *                     对角线翻折          每行左右颠倒
 *                     谜底揭晓！          目标矩阵！
 *
 * 记忆口诀：「先转后翻」
 *
 * ============================================================
 * 逐个元素追踪：为什么转置+翻转 = 顺时针90°？
 * ============================================================
 *
 * 随便跟踪一个元素，比如数字 4（原位置 [1,0]）：
 *
 *   原位置:        matrix[1][0] = 4
 *   转置:          matrix[0][1] = 4    (i,j 互换)
 *   翻转(行宽=n=3): matrix[0][3-1-1] = matrix[0][1] = 4
 *                  (列坐标从 j 变成 n-1-j)
 *
 *   所以最终: matrix[1][0] → matrix[0][n-1-1] = matrix[0][1]
 *   检查目标矩阵 [0][1] = 4 ✓
 *
 * 通用映射公式:
 *   原 matrix[i][j] → 先转置 → matrix[j][i]
 *                   → 再翻转 → matrix[j][n-1-i]
 *
 * 验证：原 [0,0]=1 → [0][2]=1  目标 [0][2]=1 ✓
 *       原 [2,1]=8 → [2][n-1-2]=[2][0]=8  目标 [2][0]=8 ✓
 *
 * ============================================================
 * 扩展：其他角度怎么转？
 * ============================================================
 *
 *  逆时针 90°:  转置 + 垂直翻转（每列首尾交换）
 *  180°:        水平翻转 + 垂直翻转
 *  270°:       顺时针 90° × 3，或者逆时针 90°
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    void rotate(vector<vector<int>>& matrix) {
        int n = matrix.size();

        // ---- 第一步：转置（对角线翻折） ----
        // 只遍历对角线右上方，避免重复交换
        //     [\ . .]
        //     [. \ .]   ← 只处理 . 的部分
        //     [. . \]
        for (int i = 0; i < n; ++i) {
            for (int j = i + 1; j < n; ++j) {
                swap(matrix[i][j], matrix[j][i]);
            }
        }

        // ---- 第二步：每行水平翻转 ----
        // 对于每一行，第 k 个和第 n-1-k 个交换
        //  [a, b, c, d] → [d, c, b, a]
        for (int i = 0; i < n; ++i) {
            for (int j = 0; j < n / 2; ++j) {
                swap(matrix[i][j], matrix[i][n - 1 - j]);
            }
        }
    }
};
// @lc code=end
