/*
 * @lc app=leetcode.cn id=38 lang=cpp
 *
 * [38] 外观数列
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做聊天系统的"垃圾消息模式识别"。
 * 玩家发送消息："1 个 a，2 个 b，1 个 c" =
 * "a b b c"。你需要对手动输入的消息进行"行程长度编码
 * (RLE, Run-Length Encoding)"模式的压缩与展开——外观数列
 * 本质上就是反复对自身做 RLE。
 *
 * 游戏开发中同样的场景：
 * - 背包压缩传输：大量相同物品可以用 (物品ID, 数量) 压缩
 * - 地形数据压缩：连续的相同地块用 RLE 存储（如 Minecraft 区块）
 * - 动画压缩：连续的相同帧/骨骼姿势可以跳过
 * - 聊天频道刷屏检测：识别"相同消息 × N 次"的模式
 * - 协议优化：网络包中连续相同值用 RLE 编码
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 外观数列是一个递归定义的序列：
 *   countAndSay(1) = "1"
 *   countAndSay(n) = 对 countAndSay(n-1) 的"读法"
 *
 * "读法"：对连续相同数字进行计数并念出来。
 *   例如 "3322251" 读作 "两个 3，三个 2，一个 5，一个 1"
 *   → "23321511"
 *
 * 示例：
 *   n=1 → "1"     （基础）
 *   n=2 → "11"    （一个 1）
 *   n=3 → "21"    （两个 1）
 *   n=4 → "1211"  （一个 2，一个 1）
 *   n=5 → "111221"（一个 1，一个 2，两个 1）
 *
 * ============================================================
 * 核心思维：双指针统计连续相同字符
 * ============================================================
 *
 * 每一轮的核心操作：给定一个字符串，输出它的"读法"。
 *
 * 比如对 "1211" 做 RLE：
 *
 *   "1 2 1 1"
 *    ↑         i=0, j 从 i 开始向右走
 *    i,j
 *
 *   "1 2 1 1"
 *    ↑ ↑       j=1, s[1]='2' != s[0]='1' → 停止
 *    i j       count = j-i = 1, 数字 = s[i]='1' → 追加 "11"
 *
 *   "1 2 1 1"
 *      ↑       i=j=1, j 继续走
 *      i,j
 *
 *   "1 2 1 1"
 *      ↑ ↑     j=2, s[2]='1' != s[1]='2' → 停止
 *      i j     count = 1, 数字 = '2' → 追加 "12"
 *
 *   "1 2 1 1"
 *        ↑     i=j=2, j 继续走
 *        i,j
 *
 *   "1 2 1 1"
 *        ↑  ↑  j=4（越界）, 停止
 *        i  j  count = j-i = 2, 数字 = '1' → 追加 "21"
 *
 *   最终输出: "11" + "12" + "21" = "111221" ✅
 *
 * ============================================================
 * 递归 vs 迭代
 * ============================================================
 *
 * 递归写法更简洁（符合数学定义），但 n 大时有栈溢出风险。
 * 这里 n <= 30，递归完全安全。如果面试官追问，可以提一下
 * 迭代版本的做法：for i = 2..n 循环调用 RLE。
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <string>
using namespace std;

// @lc code=start
class Solution {
public:
    string countAndSay(int n) {
        // ---- ① 递归基：n=1 时固定返回 "1" ----
        if (n == 1) return "1";

        // ---- ② 递归获取上一层的字符串 ----
        string prev = countAndSay(n - 1);
        string result;

        // ---- ③ 双指针做行程长度编码（RLE） ----
        int len = prev.size();
        int i = 0;
        while (i < len) {
            int j = i + 1;
            // 向右扫描，统计连续相同字符的个数
            while (j < len && prev[j] == prev[i]) {
                ++j;
            }
            // count = j - i，追加 "数量" + "字符"
            result += to_string(j - i) + prev[i];
            i = j;  // 跳到下一组
        }

        return result;
    }
};
// @lc code=end
