/*
 * @lc app=leetcode.cn id=45 lang=cpp
 *
 * [45] 跳跃游戏 II
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做动作游戏的"位移技能链"系统。
 * 角色站在平台最左边，要跳到最右边。
 * 每个位置有一个数字，代表你从这里最多能往前跳几格。
 * 问：最少跳几次能到终点？
 *
 * 游戏开发中同样的"最少步数到目标"逻辑还用在：
 * - 自动寻路的跳点优化（NavMesh 上的跳跃连接）
 * - 技能连招的最短按键序列
 * - UI 焦点移动（方向键在菜单格子间跳转的最少步数）
 * - 回合制游戏的"几步内到达敌人"判定
 * - 状态机转换：从状态 A 到状态 B 最少几个中间态
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * nums[i] = 你在位置 i 最多能跳多远（比如 3 表示可以跳到 i+1, i+2, i+3）
 * 从下标 0 出发，保证一定能到终点，求最小跳跃次数。
 *
 * 示例：
 *   nums = [2, 3, 1, 1, 4]
 *   输出: 2
 *   解释: 0→1(跳2步不够), 0→1→4(跳3步直接到终点)
 *
 * ============================================================
 * 核心思维：跳跃 = 层序遍历（BFS 的一维版本）
 * ============================================================
 *
 * 把问题换个角度看：
 *   第 0 跳：你站在起点（下标 0）
 *   第 1 跳：你能到达的所有位置 = [1, nums[0]]
 *   第 2 跳：从第 1 跳的区域出发，最远能到哪？
 *   ...
 *
 * 本质上是在数"需要几次 BFS 扩展才能覆盖到终点"！
 *
 * 画个图（nums = [2, 3, 1, 1, 4]）：
 *
 *   下标:  0   1   2   3   4
 *   nums:  2   3   1   1   4
 *
 *   第 0 跳：站在 0                      覆盖范围 [0, 0]
 *   第 1 跳：从 0 出发，最远到 2           覆盖范围 [1, 2]
 *   第 2 跳：从 1~2 出发，最远到 4(终点)   覆盖范围 [3, 4]
 *
 *   → 答案 2
 *
 * 关键洞察：
 *   不需要真的 BFS（不用队列），因为数组是连续的一维线，
 *   第 k 跳能到达的位置一定是连续的一段区间 [start, end]。
 *   所以我们只需要维护"当前跳能覆盖的边界"即可。
 *
 * ============================================================
 * 贪心算法：三个变量走完全程
 * ============================================================
 *
 *   curEnd  → 当前这一跳能到达的最远边界
 *             （走到这个边界时，说明你用完当前跳了，必须再跳一次）
 *
 *   curFarthest → 下一跳能到达的最远位置
 *                 （边走路边更新，为下一跳做准备）
 *
 *   jumps → 已跳次数
 *
 * 过程就像"开车加油"：
 *   你从起点出发，油箱能跑 curEnd 这么远。
 *   沿路你不断观察：如果在前方某个加油站加油，能跑更远吗？
 *   到了 curEnd 还没到终点 → 必须加油了（jumps++），
 *   把油箱上限更新为沿途看到的最远距离。
 *
 * 走一遍 nums = [2, 3, 1, 1, 4]：
 *
 *   i=0, nums[0]=2
 *     curFarthest = max(0, 0+2) = 2
 *     i == curEnd(0) → jump! jumps=1, curEnd=2
 *
 *   i=1, nums[1]=3
 *     curFarthest = max(2, 1+3) = 4
 *     i != curEnd(2) → 继续走
 *
 *   i=2, nums[2]=1
 *     curFarthest = max(4, 2+1) = 4
 *     i == curEnd(2) → jump! jumps=2, curEnd=4
 *
 *   此时 curEnd=4 已经是终点，循环结束（注意：不需要在终点跳）
 *   → 答案 jumps = 2
 *
 * ============================================================
 * 为什么不跳最后一步？
 * ============================================================
 *
 * 循环只到 n-2（倒数第二个位置），因为：
 *   到了终点你还跳啥？已经到了。
 *   如果 curEnd 刚好在终点，不需要再跳一次。
 *   所以 for 循环写成 i < n-1。
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    int jump(vector<int>& nums) {
        int n = nums.size();
        if (n == 1) return 0;   // 已经在终点，不需要跳

        int jumps = 0;           // 跳了多少次
        int curEnd = 0;          // 当前这一跳最远能到哪
        int curFarthest = 0;     // 下一跳最远能到哪（沿途不断刷新）

        // 只遍历到 n-2：最后一个位置不需要跳
        for (int i = 0; i < n - 1; ++i) {
            // 沿途观察：从位置 i 出发能刷新最远记录吗？
            curFarthest = max(curFarthest, i + nums[i]);

            // 走到当前跳的边界了，必须跳一次
            if (i == curEnd) {
                ++jumps;
                curEnd = curFarthest; // 下一跳的覆盖范围

                // 提前收工：下一跳已经能覆盖终点了
                if (curEnd >= n - 1) break;
            }
        }

        return jumps;
    }
};
// @lc code=end
