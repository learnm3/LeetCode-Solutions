/*
 * @lc app=leetcode.cn id=15 lang=cpp
 *
 * [15] 三数之和
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做"炼金术合成"系统。
 * 背包里有 N 种材料，每种材料有一个魔力值（正或负）。
 * 配方要求：三种材料的魔力值之和恰好为 0（正负魔力互相抵消），
 * 才能合成完美药剂。每种材料只能用一次，而且找到的组合
 * 不能重复（相同的魔力值组合只算一种）。
 *
 * 游戏开发中的同样场景：
 * - 装备属性搭配：三件装备的属性加成为 0（零和博弈）
 * - 技能强化材料：三种符文能量之和 = 目标值
 * - 交易系统：三笔交易金额平衡
 * - 数值策划：三个 BUFF 的数值之和为 0（互相克制）
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定整数数组 nums，找出所有和为 0 且不重复的三元组。
 *
 * 示例：
 *   输入: [-1, 0, 1, 2, -1, -4]
 *   输出: [[-1, -1, 2], [-1, 0, 1]]
 *
 * ============================================================
 * 核心思维：排序 + 固定一个 + 双指针找另外两个
 * ============================================================
 *
 * 暴力法：三重循环 O(n³)。
 * 聪明法：排序 O(n log n) → 固定第一个数 → 剩下两个用双指针 O(n²)。
 *
 * 排序后数组变成有序的，双指针可以利用"单调性"：
 *   和太小 → 左指针右移（增大和）
 *   和太大 → 右指针左移（减小和）
 *
 * ============================================================
 * C++ 零基础语法讲解
 * ============================================================
 */

/*
 * 【头文件】
 *   <vector>    → 动态数组
 *   <algorithm> → 算法工具（本题用到 sort()）
 */
#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【vector<vector<int>> threeSum(vector<int>& nums)】
     *
     *   返回值 vector<vector<int>>
     *     → 二维整数数组。外层每个元素是一个三元组 [a, b, c]。
     *        例: [[-1,-1,2], [-1,0,1]]
     *
     *   参数 vector<int>& nums → 整数数组的引用（不复制）
     */
    vector<vector<int>> threeSum(vector<int>& nums) {

        /*
         * 【vector<vector<int>> result;】
         *   声明最终结果容器，初始为空。
         *   类型：装"整数数组"的数组（二维）。
         *   相当于一个大篮子，里面放很多小篮子，每个小篮子装 3 个整数。
         */
        vector<vector<int>> result;

        /*
         * 【int n = nums.size();】
         *   把数组长度存到变量 n 里，后面反复用到。
         *   例：[6个元素] → n = 6。
         */
        int n = nums.size();

        /*
         * 【if (n < 3) return result;】
         *   少于 3 个数，不可能组成三元组，直接返回空的 result。
         *
         *   逐段拆解：
         *
         *   if (n < 3) → 条件判断。"n < 3" = "数组长度小于 3 吗？"
         *     < → 小于运算符。3<5→true, 5<3→false。
         *
         *   return result; → 提前退出函数。返回一个空的 vector<vector<int>>（= []）。
         *
         *   这种"提前返回"模式很常见：先处理特殊情况，避免后面白忙活。
         *
         *   n < 3 而不是 n <= 2？一样的意思。习惯写 n < 3。
         */
        if (n < 3) return result;

        /*
         * 【sort(nums.begin(), nums.end());】
         *   把整个数组从小到大排序。原地修改，不产生新数组。
         *
         *   sort → <algorithm> 提供的排序函数，时间复杂度 O(n log n)。
         *   nums.begin() → 指向数组第一个元素
         *   nums.end()   → 指向数组"最后一个元素后面"的哨兵
         *
         *   排序前: [-1, 0, 1, 2, -1, -4]
         *   排序后: [-4, -1, -1, 0, 1, 2]
         *
         *   为什么要排序？
         *     ① 相同的数字会紧挨着，方便跳过重复
         *     ② 数组成了从小到大排列，双指针才能工作
         *        （如果和太大，右移左指针让和增大；和太小，左移右指针让和减小）
         */
        sort(nums.begin(), nums.end());

        /*
         * 【for (int i = 0; i < n - 2; ++i) { ... }】
         *   外层循环：固定三元组的第一个数 nums[i]。
         *
         *   为什么 i < n - 2？
         *     三元组需要三个不同的数，所以 i 最多走到倒数第三个位置。
         *     例：n=6，i 最大到 3（即下标 0,1,2,3），给 L 和 R 留两个位置。
         */
        for (int i = 0; i < n - 2; ++i) {

            /*
             * 【if (nums[i] > 0) break;】
             *   因为数组已排序，如果最小数 nums[i] 已经大于 0，
             *   那后面的数更大，三个正数相加不可能等于 0。
             *   直接结束整个循环。
             *
             *   逐段拆解：
             *
             *   > → 大于运算符。5>0→true, -1>0→false。
             *
             *   break → 立刻跳出当前所在的循环（这里是 for 循环）。
             *           和 return 的区别：break 只跳出循环，继续执行循环后面的代码。
             *           return 会直接结束整个函数。
             *
             *           例：i=3, nums[3]=3 > 0 → break，for 循环结束。
             *
             *   这是一个剪枝优化：既然不可能有答案了，剩下的 i 都不用看了。
             */
            if (nums[i] > 0) break;

            /*
             * 【if (i > 0 && nums[i] == nums[i - 1]) continue;】
             *   跳过重复的第一个数。
             *
             *   逐段拆解：
             *
             *   i > 0 → 不是第一轮循环（第一个元素没有"上一个"，没必要比）
             *
             *   && → 逻辑与（AND）。左边 AND 右边都为 true，整体才为 true。
             *         例：true && true = true,   true && false = false
             *
             *   nums[i] == nums[i - 1] → 当前元素和前一个元素相等吗？
             *     == → 等于运算符（两个等号）。注意 != 是赋值，== 是判断相等。
             *          这是新手最容易错的地方！
             *
             *   continue → 跳过本轮循环的剩余代码，直接进入下一轮（i++然后判断条件）。
             *              和 break 的区别：break 是彻底不干了，continue 是跳过这一轮。
             *
             *              例：排序后 [-4, -1, -1, 0, 1, 2]
             *                  i=0: nums[0]=-4, i==0，跳过判断
             *                  i=1: nums[1]=-1, nums[0]≠-1，正常执行
             *                  i=2: nums[2]=-1, nums[1]==-1 → continue！跳过
             *                       （因为用 nums[1]=-1 当第一个数已经搜过了，
             *                         再用 nums[2]=-1 当第一个数会产生重复组合）
             *
             *   这是"外层去重"。
             */
            if (i > 0 && nums[i] == nums[i - 1]) continue;

            /*
             * 【int L = i + 1, R = n - 1;】
             *   初始化双指针。
             *
             *   L = i + 1  → 左指针从 i 的右边第一个开始
             *   R = n - 1  → 右指针从数组末尾开始
             *
             *   为什么 L 从 i+1 开始？
             *     因为三元组要三个不同的下标，L 必须大于 i。
             *     i 左边已经处理过了，不需要回头看。
             */
            int L = i + 1, R = n - 1;

            /*
             * 【while (L < R) { ... }】
             *   内层循环：双指针往中间移动，找两个数使三数和为 0。
             *   L < R 保证两个指针还没相遇（相遇就是同一个位置，不能算两个数）。
             */
            while (L < R) {

                /*
                 * 【int sum = nums[i] + nums[L] + nums[R];】
                 *   计算三元组的和。
                 *   + 是加法运算符，这里用了两个 + 把三个数加起来。
                 */
                int sum = nums[i] + nums[L] + nums[R];

                /*
                 * 【if (sum == 0) { ... } else if (sum < 0) { ... } else { ... }】
                 *   三路分支：根据和与 0 的大小关系决定动作。
                 *
                 *   这是 if-else if-else 链：
                 *     - 先检查第一个条件(sum==0)，true就执行它然后跳过后面
                 *     - 第一个不成立，检查第二个条件(sum<0)
                 *     - 前两个都不成立，走最后的 else（一定是 sum>0）
                 */
                if (sum == 0) {
                    /*
                     * 【result.push_back({nums[i], nums[L], nums[R]});】
                     *   找到一个解！把三元组加入结果。
                     *
                     *   .push_back() → 追加到数组末尾（和之前题一样的用法）
                     *   {a, b, c}   → C++11 初始化列表语法。
                     *                  构造一个临时的 vector<int> 包含这三个数。
                     *                  等价于：
                     *                    vector<int> triple;
                     *                    triple.push_back(a);
                     *                    triple.push_back(b);
                     *                    triple.push_back(c);
                     *                    result.push_back(triple);
                     */
                    result.push_back({nums[i], nums[L], nums[R]});

                    /*
                     * 【内层去重：跳过重复的 L 和 R】
                     *
                     *   while (L < R && nums[L] == nums[L + 1]) ++L;
                     *     只要 L 和它右边一个数相同，就一直右移 L。
                     *     因为相同的 b 值会产生相同的三元组，需要跳过。
                     *
                     *     例：排好序后 [..., -1, -1, -1, 2, ...]
                     *                           L  L+1
                     *         找到 [-1, 2] 后，下一个 L 还是 -1，
                     *         组合还是一样的 [-1, 2]，所以要跳过所有连续的 -1。
                     *
                     *   while (L < R && nums[R] == nums[R - 1]) --R;
                     *     同理，跳过 R 左边所有和 R 相同的值。
                     *
                     *   L < R 这个附加条件 → 防止指针越界或交错。
                     *     && 是"短路"的：左边 false 就不会执行右边。
                     */
                    while (L < R && nums[L] == nums[L + 1]) ++L;
                    while (L < R && nums[R] == nums[R - 1]) --R;

                    /*
                     *   ++L; --R;
                     *     跳过重复后，还要各自再走一步——因为当前这对 L,R
                     *     已经用过了，必须移动才能找新的组合。
                     */
                    ++L;
                    --R;

                } else if (sum < 0) {
                    /*
                     *   sum < 0 → 和太小了。
                     *   因为数组排过序，L 越大值越大，所以 L 右移来增大和。
                     */
                    ++L;

                } else {
                    /*
                     *   既不是 ==0 也不是 <0，那一定是 >0。
                     *   和太大了。R 左移来减小和。
                     */
                    --R;
                }
            }
        }

        /*
         * 【return result;】
         *   返回所有找到的不重复三元组。
         */
        return result;
    }
};
// @lc code=end
