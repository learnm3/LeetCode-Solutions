/*
 * @lc app=leetcode.cn id=560 lang=cpp
 *
 * [560] 和为 K 的子数组
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做战斗日志的"伤害区间统计"系统。
 * 战斗日志记录了过去 30 秒内每秒的净伤害值（有正有负）：
 *   [1, 2, -1, 3, -2, 1, ...]
 * 策划想知道："有多少个连续时间段的总伤害恰好等于 K？"
 *
 * 这就是"和为 K 的子数组"——找出所有连续子数组，
 * 其元素之和恰好等于目标值 K。
 *
 * 注意：子数组必须是"连续的"，不能跳着选。
 *
 * 游戏开发中的同样场景：
 * - 经济曲线：找出净金币变化恰好为 K 的所有连续时段
 * - 成就系统：在线时长恰好累积到 K 分钟的所有连续签到段
 * - 性能分析：CPU 占用恰好达到阈值的所有连续采样区间
 * - 任务进度：贡献值恰好为目标值的所有连续任务段
 * - 匹配系统：战力差距之和恰好为 K 的连续队伍段
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给定整数数组 nums 和整数 k，统计和为 k 的连续子数组个数。
 *
 * 示例：
 *   输入: nums = [1, 1, 1], k = 2
 *   输出: 2  （[1,1] 出现在下标 0~1 和下标 1~2，共 2 个）
 *
 *   输入: nums = [1, 2, 3], k = 3
 *   输出: 2  （[1,2] 和 [3]）
 *
 * ============================================================
 * 核心思维：前缀和 + 哈希表 = 两数之和的变体
 * ============================================================
 *
 * 先理解"前缀和"：
 *
 *   nums:   [1,  2,  -1,  3]
 *   prefix: [0, 1,  3,  2,  5]  ← prefix[i] = nums[0..i-1] 的和
 *             ↑                  ← prefix[0] = 0（空数组的和）
 *
 *   子数组 nums[1..2] = [2, -1] 的和 = 1
 *   用前缀和计算：prefix[3] - prefix[1] = 2 - 1 = 1
 *               （前3个的和 - 前1个的和 = 中间2个的和）
 *
 *   通用公式：
 *     nums[i..j-1] 的和 = prefix[j] - prefix[i]
 *
 * 问题转化成：
 *   找多少对 (i, j) 满足 prefix[j] - prefix[i] = k，且 i < j
 *
 *   变形：prefix[i] = prefix[j] - k
 *   意思：遍历到 j 时，看看之前有多少个前缀和等于 (当前前缀和 - k)。
 *
 *   这不就是两数之和吗！
 *     两数之和: 当前数 = x，找之前有没有 (target - x)
 *     本题:     当前前缀和 = cur，找之前有多少个 (cur - k)
 *
 * 唯一区别：两数之和只要找一个，本题要统计"有多少个"。
 *           所以哈希表的值从下标改为"出现次数"。
 *
 * 图解 nums = [1, 2, -1, 3], k = 2：
 *
 *   遍历:          哈希表(count)          cur   cur-k  找到?
 *   ─────────────────────────────────────────────────────
 *   初始:          map[0]=1（空数组）
 *   i=0: cur=1     map: {0:1}             1     -1    无 → map[1]=1
 *   i=1: cur=3     map: {0:1, 1:1}       3      1    有! 找到1次 → count++
 *                                         map[3]=1
 *   i=2: cur=2     map: {0:1, 1:1, 3:1}  2      0    有! 找到1次 → count++
 *                                         map[2]=1
 *   i=3: cur=5     map: {0:1,1:1,3:1,2:1} 5     3    有! 找到1次 → count++
 *                                         map[5]=1
 *
 *   count = 3
 *   验证: [1,2,-1]和=2, [2]和=2, [1,2,-1,?]... 等等
 *   实际是: [1,2,-1]✓, [-1,3]✓, [2]✓ → 3个 ✓
 *
 * ============================================================
 * C++ 零基础语法讲解
 * ============================================================
 */

/*
 * 【头文件】
 *   <vector>        → 动态数组
 *   <unordered_map> → 哈希表（键→值，O(1)查询）
 */
#include <vector>
#include <unordered_map>
using namespace std;

// @lc code=start
class Solution {
public:
    /*
     * 【int subarraySum(vector<int>& nums, int k)】
     *
     *   返回值 int → 整数（满足条件的子数组个数）
     *   参数 nums → 整数数组
     *   参数 k    → 目标和
     */
    int subarraySum(vector<int>& nums, int k) {

        /*
         * 【int count = 0;】
         *   计数器，统计有多少个子数组和为 k。
         *   初始为 0（还没开始找）。
         */
        int count = 0;

        /*
         * 【int curSum = 0;】
         *   当前前缀和。一边遍历一边累加。
         *   curSum 就是 prefix[j]（当前遍历到 j 时的前缀和）。
         *   初始为 0（什么都没加）。
         */
        int curSum = 0;

        /*
         * 【unordered_map<int, int> prefixCount;】
         *   哈希表：统计每种前缀和出现了多少次。
         *
         *   类型拆解：unordered_map<键, 值>
         *     键 = int → 前缀和的值
         *     值 = int → 这个前缀和出现了多少次
         *
         *   和两数之和的区别：
         *     两数之和的 map: 键=数字值, 值=下标（只要一个）
         *     本题的 map:     键=前缀和,   值=出现次数（要统计有多少个）
         */
        unordered_map<int, int> prefixCount;

        /*
         * 【prefixCount[0] = 1;】
         *   初始化：前缀和为 0 的情况出现 1 次。
         *
         *   为什么？
         *     这代表"空数组"（一个元素都不选）的前缀和。
         *     如果某个子数组从下标 0 开始，它的前缀和 - 0 = 它自己。
         *     比如 nums = [2] 整体就是一个和为 2 的子数组，
         *     此时 curSum=2, curSum-k=0，需要 map 里有 0 才能匹配上。
         *
         *   [] 操作 → 如果键 0 不存在，自动创建它并返回引用，
         *              然后 = 1 给它赋初值。
         */
        prefixCount[0] = 1;

        /*
         * 【for (int num : nums) { ... }】
         *   范围 for 循环：遍历 nums 里的每个整数。
         *   每次循环，num 是当前的元素值。
         *
         *   注意：不用下标 i，因为我们只需要前缀和的值。
         */
        for (int num : nums) {

            /*
             * 【curSum += num;】
             *   累加当前元素到前缀和。
             *
             *   += → 加等于。curSum += num 等价于 curSum = curSum + num。
             *
             *   例：curSum=3, num=-1 → curSum = 3 + (-1) = 2
             */
            curSum += num;

            /*
             * 【int need = curSum - k;】
             *   我需要找的前缀和。
             *
             *   推导：
             *     设之前某个前缀和 = X，当前前缀和 = curSum
             *     中间子数组和 = curSum - X
             *     我们需要 curSum - X = k
             *     → X = curSum - k
             *
             *   所以 need = curSum - k，看这个值之前出现过几次。
             */
            int need = curSum - k;

            /*
             * 【if (prefixCount.count(need)) { ... }】
             *   检查 need 这个前缀和在哈希表里出现过吗？
             *
             *   .count(need) → 返回 1（存在）或 0（不存在）。
             *   和之前题目的 .count() 用法完全一样。
             */
            if (prefixCount.count(need)) {

                /*
                 * 【count += prefixCount[need];】
                 *   把 need 前缀和的出现次数加到 count 上。
                 *
                 *   逐段拆解：
                 *
                 *   prefixCount[need] → [] 访问哈希表，返回键 need 对应的值。
                 *                        键 = 某个前缀和的值
                 *                        值 = 这个前缀和之前出现过多少次
                 *
                 *   为什么是"加"而不是"count = 1"？
                 *     因为前面可能有多个位置的前缀和都等于 need！
                 *     每个位置都可以和当前位置组成一个满足条件的子数组。
                 *
                 *     例：need=5 之前出现过 3 次，那么就有 3 个不同的起点
                 *         可以和当前位置组成和为 k 的子数组。
                 *
                 *   += → count = count + 那个次数
                 */
                count += prefixCount[need];
            }

            /*
             * 【++prefixCount[curSum];】
             *   把当前前缀和登记到哈希表里，出现次数 +1。
             *
             *   为什么是 ++（自增）？
             *     prefixCount[curSum] 原本可能是 0（从未出现过），
             *     ++ 后变成 1（第一次出现）。
             *     如果以前出现过 2 次，++ 后变成 3（又出现了一次）。
             *
             *   等价于：
             *     prefixCount[curSum] = prefixCount[curSum] + 1;
             *
             *   为什么先查 need，再登记自己？
             *     因为子数组不能为空！你不能用当前前缀和自己匹配自己。
             *     所以先查"之前有没有 need"，登记"我来过了"留给后面的人。
             */
            ++prefixCount[curSum];
        }

        /*
         * 【return count;】
         *   返回统计到的满足条件的子数组总数。
         */
        return count;
    }
};
// @lc code=end
