/*
 * @lc app=leetcode.cn id=27 lang=cpp
 *
 * [27] 移除元素
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】你在开发一款射击游戏的"物品栏过滤系统"。
 * 玩家背包中存储了大量的物品数据（数组形式），其中某些物品被标记为
 * "已过期/已使用"（值为特定标记）。背包整理时，需要将所有已过期的物品
 * 从物品栏中移除，保留有效物品，并返回有效物品的数量。
 * 这就是"移除元素"问题。
 *
 * 另一个情境：MOBA 游戏的小地图上，需要将"已死亡"的单位标记从
 * 活跃单位列表中移除，保留存活的单位。
 *
 * 【题目】给定数组 nums 和值 val，原地移除所有值等于 val 的元素，
 * 返回移除后的新长度。元素的顺序可以改变。
 * 示例：
 *   输入：nums = [3,2,2,3], val = 3
 *   输出：2, nums = [2,2,_,_]
 *   输入：nums = [0,1,2,2,3,0,4,2], val = 2
 *   输出：5, nums = [0,1,3,0,4,_,_,_]
 *
 * ===== 核心思维 =====
 *
 * 双指针（快慢指针）——与"删除重复项"几乎一样：
 *
 * 想象你要清理一排盒子，把标签是"val"的盒子扔到后面。
 *
 * 慢指针 slow：指向"已整理好的有效区域"的下一个空位
 * 快指针 fast：扫描整个数组
 *
 * 如果 nums[fast] != val：是有效元素，搬到 slow 位置，slow++
 * 如果 nums[fast] == val：是要删除的元素，直接跳过（fast++ 继续）
 *
 * 图解（nums = [3,2,2,3], val = 3）：
 *   初始：slow=0, fast=0
 *   [3, 2, 2, 3]
 *    s
 *    f
 *   nums[0]==3，跳过
 *
 *   [3, 2, 2, 3]
 *    s  f
 *   nums[1]!=3，搬到 slow：nums[0]=2，slow++
 *   [2, 2, 2, 3]
 *       s
 *       f
 *
 *   nums[2]!=3，搬到 slow：nums[1]=2，slow++
 *   [2, 2, 2, 3]
 *          s
 *          f
 *   nums[3]==3，跳过
 *
 *   结果：长度 slow=2，前面是 [2,2]
 *
 * 和"删除重复项"的区别：判断条件不同
 *   - 删除重复项：nums[fast] != nums[slow]（和已保留的最后一个比较）
 *   - 移除元素：   nums[fast] != val（和固定值比较）
 *
 * ===== 可迁移的解题模式 =====
 *
 * "原地过滤数组"模式——核心三要素：
 *   1. slow 指针追踪"有效区域"长度
 *   2. fast 指针扫描全部元素
 *   3. 条件判断决定是否"搬运"
 *
 * 同类问题：
 *   - 移动零（变体：移除 0 后补 0）
 *   - 删除有序数组中的重复项（条件变为和前一个不同）
 *   - 删除有序数组中的重复项 II（条件变为出现次数 <= 2）
 *   - 游戏中过滤背包中的过期道具
 *   - 聊天系统中过滤被屏蔽玩家的消息
 *   - 渲染列表中剔除不可见的对象
 */

#include <vector>
using namespace std;

// @lc code=start
class Solution {
public:
    int removeElement(vector<int>& nums, int val) {
        int slow = 0; // 有效区域的末尾索引（下一个可放置的位置）

        // fast 扫描整个数组
        for (int fast = 0; fast < nums.size(); fast++) {
            // 不是要删除的元素，就保留
            if (nums[fast] != val) {
                nums[slow] = nums[fast];
                slow++;
            }
            // 是要删除的元素，直接跳过（不保留）
        }

        return slow; // 有效元素的数量
    }
};
// @lc code=end
