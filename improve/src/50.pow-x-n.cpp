/*
 * @lc app=leetcode.cn id=50 lang=cpp
 *
 * [50] Pow(x, n)
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 你正在做放置游戏的"暴击伤害复合计算"系统。
 * 玩家的暴击倍率是 1.5，连续暴击 10 次，总倍率 = 1.5^10。
 * 策划可能把 n 设到几十甚至上百（BUFF 叠加层数），
 * 你不可能真的乘 100 次——O(n) 太慢了。
 *
 * 游戏开发中同样的"快速幂"场景：
 * - 伤害公式中的复合加成：(1+bonus)^层数
 * - 经济系统利息计算：本金 × (1+r)^天数
 * - 属性递减公式：a × (0.9)^等级
 * - 概率计算：独立事件全触发的概率 = p^n
 * - 装备强化：成功率 0.8^(强化次数)
 * - 指数衰减：粒子大小/颜色随时间缩小
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 实现 pow(x, n)，计算 x 的 n 次方。
 * n 可以是负数（x^(-n) = 1 / x^n）。
 *
 * 约束：-100.0 < x < 100.0, -2^31 <= n <= 2^31-1
 *
 * ============================================================
 * 核心思维：每次把问题规模砍一半（二分/快速幂）
 * ============================================================
 *
 * 朴素想法：
 *   x^10 = x × x × x × ... × x   （乘 10 次）
 *   太慢了。
 *
 * 聪明想法：
 *   利用 x^n = (x^2)^(n/2) 这条公式，每次把指数砍半。
 *
 *   x^10 = (x^2)^5           ← 指数从 10 变 5，底数翻倍
 *        = x^2 × (x^2)^4     ← 5 是奇数，拆一个出来
 *        = x^2 × (x^4)^2     ← 指数从 4 变 2
 *        = x^2 × (x^8)^1     ← 指数从 2 变 1
 *        = x^2 × x^8 × (x^8)^0  ← 拆出最后一个
 *        = x^10 ✓
 *
 *   只用了 4 步（而不是 10 步）！
 *
 * 规律：
 *   n 是偶数 → x^n = (x×x)^(n/2)，指数直接砍半
 *   n 是奇数 → x^n = x × (x×x)^((n-1)/2)，拆一个 x 出来再砍半
 *   n = 0   → 结果是 1
 *   n < 0   → 算 x^|n|，然后取倒数
 *
 * 画成递归树（x^10 为例）：
 *
 *   myPow(x, 10)
 *     → myPow(x², 5)        ← 偶数，指数砍半
 *       → x² × myPow(x⁴, 2) ← 奇数，拆一个出来
 *         → myPow(x⁸, 1)    ← 偶数，砍半
 *           → x⁸ × myPow(.., 0) ← 奇数，拆一个
 *             → return 1    ← 到底了
 *
 * 回溯（把结果拼起来）：
 *   底 → 1
 *   上 → x⁸ × 1 = x⁸
 *   上 → x⁴⁺⁸ = x⁸? 不对...
 *
 * 实际回溯：
 *   level 0: 1
 *   level 1: x⁸ × 1 = x⁸
 *   level 2: 1 × x⁸ = x⁸  (n=2偶数，不拆，result=1×x⁸)
 *   level 3: x² × x⁸ = x¹⁰  (n=5奇数，拆，result=x²×x⁸)
 *   level 4: 返回 x¹⁰
 *
 * ============================================================
 * 迭代版（更直观的写法）
 * ============================================================
 *
 * 递归能写但面试最好用迭代，避免爆栈。
 *
 * 把指数看成二进制：
 *   n=10 = 二进制 1010
 *
 *   10 = 8 + 2 = 2³ + 2¹
 *
 *   所以 x^10 = x^8 × x^2
 *
 * 算法：从低到高扫二进制的每一位——
 *   - 当前位是 1 → 把当前底数乘进结果
 *   - 当前位是 0 → 不乘
 *   - 底数自乘（x → x² → x⁴ → x⁸ → ...）
 *
 * 走一遍 n=10(1010)：
 *
 *   初始: result=1, cur=x
 *
 *   n=10, 最低位=0 → result不变(=1), cur=x², n=5
 *   n=5,  最低位=1 → result=1×x²=x², cur=x⁴, n=2
 *   n=2,  最低位=0 → result不变(=x²), cur=x⁸, n=1
 *   n=1,  最低位=1 → result=x²×x⁸=x¹⁰, cur=x¹⁶, n=0
 *
 *   返回 x¹⁰ ✓
 *
 * ============================================================
 * 面试坑点：int 溢出
 * ============================================================
 *
 * n 的范围是 [-2^31, 2^31-1]。
 * 当 n = -2^31 = -2147483648 时，直接写 n = -n 会溢出
 * （因为 2147483648 > INT_MAX 2147483647）。
 *
 * 解决办法：用 long long 存 n，或者先把 n 转成 long long。
 */

#include <cstdint>
using namespace std;

// @lc code=start
class Solution {
public:
    double myPow(double x, int n) {
        // 用 long long 防止 INT_MIN 取相反数时溢出
        long long exp = n;

        // 负数指数：转成正数计算，最后取倒数
        if (exp < 0) {
            x = 1.0 / x;
            exp = -exp;
        }

        double result = 1.0;  // 结果的"容器"
        double cur = x;       // 当前底数：x → x² → x⁴ → x⁸ → ...

        // 逐位扫描指数的二进制
        while (exp > 0) {
            // 当前最低位是 1 → 把当前底数乘进结果
            if (exp & 1) {
                result *= cur;
            }
            // 底数自乘一次 = 指数翻倍
            cur *= cur;
            // 右移一位 = 看下一位二进制
            exp >>= 1;
        }

        return result;
    }
};
// @lc code=end
