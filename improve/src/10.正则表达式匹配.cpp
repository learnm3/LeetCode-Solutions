/*
 * @lc app=leetcode.cn id=10 lang=cpp
 *
 * [10] 正则表达式匹配
 *
 * ===== 游戏客户端开发面试情境题 =====
 *
 * 【情境】聊天系统的敏感词模式匹配
 *
 * 你正在为社交游戏开发聊天过滤器。系统需要支持通配符模式匹配，
 * 规则如下：
 *   - '.' 匹配任意单个字符（如 "h.t" 匹配 "hat", "hot", "hit"）
 *   - '*' 匹配零个或多个前面的那个字符（如 "ha*t" 匹配 "ht", "hat", "haaat"）
 *   - 模式必须完全匹配整个字符串（不能只匹配部分）
 *
 * 例如，玩家输入 "hello"，你需要在禁词表中查找模式 "h.*o" 是否匹配。
 * 这其实就是正则表达式（. 和 *）的最小实现，也即 LeetCode 第 10 题。
 *
 * 游戏开发中的类比场景：
 * - 对话树匹配：NPC 对话选项的模式匹配 "我需要*药水" 触发商人回复
 * - 物品名称搜索：背包搜索 "龙*剑" 匹配 "龙牙剑"、"龙骨剑"、"龙火之剑"
 * - 成就条件判定：击杀模式 "slime*king" 匹配任意等级的史莱姆王
 * - 命令别名："/cast fire*" 匹配 "/cast fireball" 或 "/cast firewall"
 *
 * 【题目】
 * 给定一个字符串 s 和一个字符模式 p，实现支持 '.' 和 '*' 的正则表达式匹配。
 * '.' 匹配任意单个字符。
 * '*' 匹配零个或多个前面的那个元素。
 * 匹配应该覆盖整个字符串，而不是部分。
 *
 * 示例：
 *   输入: s = "aa", p = "a"
 *   输出: false  （"a" 不匹配整个 "aa"）
 *
 *   输入: s = "aa", p = "a*"
 *   输出: true   （'*' 表示重复 'a' 零次或多次，这里重复 2 次）
 *
 *   输入: s = "ab", p = ".*"
 *   输出: true   （".*" 表示任意字符出现任意次数）
 *
 *   输入: s = "aab", p = "c*a*b"
 *   输出: true   （'c' 重复 0 次，'a' 重复 2 次，'b' 单次匹配）
 *
 * ===== 核心思维 =====
 *
 * 一、动态规划状态定义
 *
 * dp[i][j] = s 的前 i 个字符能否被 p 的前 j 个字符匹配
 * （i 和 j 是长度，不是下标。dp[0][0] 表示两个空串匹配）
 *
 * 二、状态转移分析
 *
 * 关键在于 p[j-1]（模式的第 j 个字符）是什么：
 *
 * 【情况1】p[j-1] 是普通字母（非 '.' 非 '*'）
 *   需要 s[i-1] == p[j-1]，且前面也要匹配：
 *   dp[i][j] = (s[i-1] == p[j-1]) && dp[i-1][j-1]
 *
 * 【情况2】p[j-1] 是 '.'
 *   '.' 匹配任意字符，所以只要前面匹配就行：
 *   dp[i][j] = dp[i-1][j-1]
 *
 * 【情况3】p[j-1] 是 '*'（最复杂的情况）
 *   '*' 不能独立存在，它修饰前一个字符 p[j-2]。
 *   有两种子情况：
 *
 *   3a. 匹配零次：忽略 p[j-2] 和 p[j-1]（即忽略 "x*" 这个组合）
 *       dp[i][j] = dp[i][j - 2]
 *
 *   3b. 匹配一次或多次：前提是 s[i-1] 能和 p[j-2] 匹配
 *       （即 s[i-1] == p[j-2] 或 p[j-2] == '.'）
 *       此时 s 消耗一个字符，p 的 "x*" 还可以继续用：
 *       dp[i][j] = matches(s[i-1], p[j-2]) && dp[i-1][j]
 *
 *   综合：dp[i][j] = dp[i][j-2] || (matches(i-1, j-2) && dp[i-1][j])
 *
 * 三、初始化
 *
 *   dp[0][0] = true  （空串匹配空模式）
 *
 *   对于 dp[0][j]（s 为空，p 非空）：只有 "x*" 结构的模式能匹配空串
 *   例如 p = "a*b*" 可以匹配空串（a 出现 0 次，b 出现 0 次）
 *   if p[j-1] == '*' then dp[0][j] = dp[0][j-2]
 *
 * 四、可视化 DP 表格
 *
 *   s="aab", p="c*a*b"
 *
 *        ""  c   *   a   *   b
 *    ""  1   0   1   0   1   0    ← dp[0][j]: "c*" 和 "c*a*" 能匹配空
 *    a   0   0   0   1   1   0    ← dp[1][3]=1: "a"="a"
 *    a   0   0   0   0   1   0    ← dp[2][4]=1: "aa"="a*"
 *    b   0   0   0   0   0   1    ← dp[3][5]=1: 整体匹配!
 *
 * 五、复杂度分析
 *
 *   - 时间复杂度：O(m*n)，填充 m*n 的 DP 表格。
 *   - 空间复杂度：O(m*n)，可优化到 O(n) 但代码可读性优先。
 *
 * 六、可迁移模式 —— 字符串匹配 DP
 *
 * DP 在字符串匹配问题中的常见模式：
 *   dp[i][j] = 前 i 个字符和前 j 个模式是否匹配
 *
 * 相关题：
 *   - 44. 通配符匹配（'?' 和 '*'，语义略有不同）
 *   - 72. 编辑距离（插入/删除/替换的 DP）
 *   - 115. 不同的子序列（计数型 DP）
 *   - 139. 单词拆分（类似模式匹配的 DP）
 *
 * 核心技巧：遇到 '*' 时，画决策树——用零次 vs 用一次（然后继续用）。
 */

#include <string>
#include <vector>
using namespace std;

// @lc code=start
class Solution {
public:
    bool isMatch(string s, string p) {
        int m = s.length(), n = p.length();

        // 辅助函数：检查 s 的第 i 个字符能否与 p 的第 j 个字符匹配
        // i, j 是"第几个"（1-indexed），内部转 0-indexed
        auto matches = [&](int i, int j) -> bool {
            if (i == 0) return false;          // s 为空，无法匹配任何字符
            if (p[j - 1] == '.') return true;   // '.' 万能匹配
            return s[i - 1] == p[j - 1];        // 普通字符直接比较
        };

        // dp[i][j]: s[0..i-1] 能否被 p[0..j-1] 匹配
        vector<vector<bool>> dp(m + 1, vector<bool>(n + 1, false));
        dp[0][0] = true; // 空串匹配空模式

        // 初始化第 0 行：s 为空，p 只能通过 "x*" 结构匹配
        for (int j = 2; j <= n; ++j) {
            if (p[j - 1] == '*') {
                dp[0][j] = dp[0][j - 2]; // 忽略 "x*" 组合
            }
        }

        // 填充 DP 表
        for (int i = 1; i <= m; ++i) {
            for (int j = 1; j <= n; ++j) {
                if (p[j - 1] == '*') {
                    // 情况A：'*' 匹配零次 → 忽略 "x*" 这对
                    dp[i][j] = dp[i][j - 2];
                    // 情况B：'*' 匹配一次或多次 → s 的当前字符匹配 x，且 s 前移
                    if (matches(i, j - 1)) {
                        dp[i][j] = dp[i][j] || dp[i - 1][j];
                    }
                } else {
                    // 普通字符或 '.'：当前字符匹配，且前面的也匹配
                    if (matches(i, j)) {
                        dp[i][j] = dp[i - 1][j - 1];
                    }
                }
            }
        }
        return dp[m][n];
    }
};
// @lc code=end
