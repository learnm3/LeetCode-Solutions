/*
 * @lc app=leetcode.cn id=57 lang=cpp
 *
 * [57] 插入区间
 *
 * ============================================================
 * 游戏客户端开发面试情境题
 * ============================================================
 *
 * 【情境】
 * 接上一题（56），BUFF 时间轴已经排好了（无重叠、按起点排序）。
 * 现在玩家又喝了一瓶药水，产生一个新的 BUFF 时间段。
 * 你需要把这个新区间插入已有的时间轴中，如果有重叠就合并。
 *
 * 注意和 56 题的区别：
 *   56: 给一堆乱序区间 → 排序 → 合并（O(n log n)）
 *   57: 区间已经排好无重叠 → 只需插入一个 → 可以 O(n)
 *
 * 游戏开发中同样的"向有序列表中插入"场景：
 * - 在已排好的技能时间线中插入一个新技能
 * - 关卡编辑器中插入一个触发区域（已有区域已排序）
 * - 音频时间轴上插入一段新音效
 * - 任务系统中插入一个新任务的时间窗口
 * - 战斗回放中插入一个新事件
 *
 * ============================================================
 * 题目
 * ============================================================
 *
 * 给一个无重叠、按起点排序的区间数组，插入新区间 newInterval。
 * 若有重叠则合并，返回插入后的新区间数组。
 *
 * 示例：
 *   输入: intervals = [[1,3],[6,9]], newInterval = [2,5]
 *   输出: [[1,5],[6,9]]  （[1,3] 和 [2,5] 重叠，合并为 [1,5]）
 *
 *   输入: intervals = [[1,2],[3,5],[6,7],[8,10],[12,16]], newInterval = [4,8]
 *   输出: [[1,2],[3,10],[12,16]]  （[3,5][6,7][8,10] 都和 [4,8] 重叠，合并为 [3,10]）
 *
 * ============================================================
 * 核心思维：三段式处理
 * ============================================================
 *
 * 因为原数组已经排好序且无重叠，新区间只会影响"中间重叠段"。
 * 整个过程分三段：
 *
 *   第①段: 完全在新区间左边的 → 直接加入结果
 *   第②段: 和新区间有重叠的 → 不断拉伸新区间
 *   第③段: 完全在新区间右边的 → 直接加入结果
 *
 * 图解：intervals = [[1,2],[3,5],[6,7],[8,10],[12,16]], new=[4,8]
 *
 *   [1,2]     [3,5] [6,7] [8,10]    [12,16]
 *    ←①→      ←────②重叠拉伸────→    ←③→
 *   直接加     合并成 [3,10]           直接加
 *
 * 结果: [[1,2], [3,10], [12,16]]
 *
 * 判断条件一句话：
 *   interval.end < new.start    → ① 完全在左边，直接加
 *   interval.start > new.end    → ③ 完全在右边（后面的全是）
 *   否则                        → ② 重叠！拉伸 new = [min,max]
 *
 * ============================================================
 * 代码分步讲解
 * ============================================================
 */

#include <vector>
#include <algorithm>
using namespace std;

// @lc code=start
class Solution {
public:
    vector<vector<int>> insert(vector<vector<int>>& intervals,
                               vector<int>& newInterval) {
        vector<vector<int>> result;
        int i = 0, n = intervals.size();

        // ---- 第①段：完全在新区间左边，不重叠 ----
        while (i < n && intervals[i][1] < newInterval[0]) {
            result.push_back(intervals[i]);
            ++i;
        }

        // ---- 第②段：和新区间重叠，不断拉伸新区间 ----
        while (i < n && intervals[i][0] <= newInterval[1]) {
            newInterval[0] = min(newInterval[0], intervals[i][0]);
            newInterval[1] = max(newInterval[1], intervals[i][1]);
            ++i;
        }
        result.push_back(newInterval);  // 合并后的区间加入结果

        // ---- 第③段：完全在新区间右边 ----
        while (i < n) {
            result.push_back(intervals[i]);
            ++i;
        }

        return result;
    }
};
// @lc code=end
